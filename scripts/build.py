#!/usr/bin/env python3
"""Regency build: regenerate everything derived from library/registry.json.

Derived artefacts (never edit by hand):
  commands/<id>/<sub>.md   nested alias commands  -> /regency:<id>:<sub>
  dispatch tables          between the markers  <!-- regency:dispatch:begin --> ... <!-- regency:dispatch:end -->
                           in README.md, CLAUDE.md and skills/regency/SKILL.md
  return templates         between the markers  <!-- regency:return:begin[ direct] --> ... <!-- regency:return:end -->
                           in library/subagents/suba-*/SKILL.md, from each suba's contract.json (scripts/returns.py)

Usage (from anywhere; the root is found relative to this file):
  python scripts/build.py          write
  python scripts/build.py --check  write nothing; exit 1 if anything is out of date

Pure standard library, Python 3.8+. No absolute paths, no network.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "library" / "registry.json"
GENERATED_MARK = "<!-- generated by scripts/build.py from library/registry.json; do not edit -->"
BEGIN = "<!-- regency:dispatch:begin -->"
END = "<!-- regency:dispatch:end -->"
TABLE_FILES = ["README.md", "CLAUDE.md", "skills/regency/SKILL.md"]
SUBAGENTS = ROOT / "library" / "subagents"
RETURN_MARK = "<!-- regency:return:begin"
RETURN_BLOCK = re.compile(r"(<!-- regency:return:begin( direct)? -->)\n.*?(<!-- regency:return:end -->)", re.S)


def load():
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def problems(reg):
    out = []
    seen = set()
    for c in reg["commands"]:
        if c["id"] in seen:
            out.append(f"duplicate command id: {c['id']}")
        seen.add(c["id"])
        if not (ROOT / "skills" / c["skill"] / "SKILL.md").is_file():
            out.append(f"command '{c['id']}': skills/{c['skill']}/SKILL.md is missing")
        subs = [s["id"] for s in c.get("subs", [])]
        if len(subs) != len(set(subs)):
            out.append(f"command '{c['id']}': duplicate sub ids")
    return out


def alias_text(reg, c, s):
    plugin = reg["plugin"]
    args = s.get("args", "")
    # JSON strings are valid YAML double-quoted scalars: a ': ' or a leading '[' in the text can no longer
    # break the frontmatter (an unquoted one makes the runtime drop ALL the frontmatter fields).
    hint = f"argument-hint: {json.dumps(args, ensure_ascii=False)}\n" if args else ""
    desc = json.dumps(f"{s['summary']} (alias of /{plugin}:{c['id']} {s['id']})", ensure_ascii=False)
    return (
        "---\n"
        f"description: {desc}\n"
        f"{hint}"
        "disable-model-invocation: true\n"
        "---\n"
        f"{GENERATED_MARK}\n\n"
        f"Run the `{plugin}:{c['skill']}` skill with the subcommand `{s['id']}` "
        "and these arguments: $ARGUMENTS\n\n"
        f"If the Skill tool is unavailable, read `${{CLAUDE_PLUGIN_ROOT}}/skills/{c['skill']}/SKILL.md` "
        "and follow it as a playbook, with the same subcommand and arguments.\n"
    )


def desired_aliases(reg):
    files = {}
    for c in reg["commands"]:
        for s in c.get("subs", []):
            files[Path("commands") / c["id"] / f"{s['id']}.md"] = alias_text(reg, c, s)
    return files


def esc(text):
    return text.replace("|", "\\|")


def table(reg):
    p = reg["plugin"]
    rows = ["| Command | What it does | Arguments | Playbook (no-plugin fallback) |",
            "|---|---|---|---|"]
    for c in reg["commands"]:
        name = f"/{p}" if c.get("bare") else f"/{p}:{c['id']}"
        rows.append(f"| `{name}` | {esc(c['summary'])} | `{esc(c.get('args', ''))}` | `skills/{c['skill']}/SKILL.md` |")
        for s in c.get("subs", []):
            a = esc(s.get("args", ""))
            rows.append(f"| `/{p}:{c['id']}:{s['id']}` | {esc(s['summary'])} | `{a}` | same playbook, subcommand `{s['id']}` |")
    return "\n".join(rows)


def render_marked(text, tbl):
    if BEGIN not in text or END not in text:
        return None
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{tbl}\n{END}{tail}"


def render_returns(text, name):
    """The spine with every return block regenerated from the suba's contract.json."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import returns  # noqa: E402  (stdlib-only sibling: the template is the contract's, not build.py's)
    return RETURN_BLOCK.sub(lambda m: f"{m.group(1)}\n{returns.spine_block(name, bool(m.group(2)), ROOT)}\n{m.group(3)}", text)


def main(check):
    reg = load()
    errs = problems(reg)
    if errs:
        print("registry problems:")
        for e in errs:
            print("  -", e)
        return 1
    stale = []

    # 1. alias commands
    want = desired_aliases(reg)
    for rel, body in want.items():
        path = ROOT / rel
        have = path.read_text(encoding="utf-8") if path.is_file() else None
        if have != body:
            stale.append(str(rel).replace("\\", "/"))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(body, encoding="utf-8", newline="\n")
    cmd_dir = ROOT / "commands"
    if cmd_dir.is_dir():
        for f in sorted(cmd_dir.rglob("*.md")):
            rel = f.relative_to(ROOT)
            if rel not in want and GENERATED_MARK in f.read_text(encoding="utf-8"):
                stale.append(f"{str(rel).replace(chr(92), '/')} (orphan alias)")
                if not check:
                    f.unlink()
        if not check:
            for d in sorted([x for x in cmd_dir.rglob("*") if x.is_dir()], reverse=True):
                if not any(d.iterdir()):
                    d.rmdir()

    # 2. dispatch tables
    tbl = table(reg)
    for rel in TABLE_FILES:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        new = render_marked(text, tbl)
        if new is None:
            stale.append(f"{rel} (dispatch markers missing)")
        elif new != text:
            stale.append(rel)
            if not check:
                path.write_text(new, encoding="utf-8", newline="\n")

    # 3. subagent return templates
    for spine in sorted(SUBAGENTS.glob("suba-*/SKILL.md")) if SUBAGENTS.is_dir() else []:
        if not (spine.parent / "contract.json").is_file():
            continue
        rel = spine.relative_to(ROOT).as_posix()
        text = spine.read_text(encoding="utf-8")
        if RETURN_MARK not in text:
            stale.append(f"{rel} (return markers missing)")
            continue
        new = render_returns(text, spine.parent.name)
        if new != text:
            stale.append(rel)
            if not check:
                spine.write_text(new, encoding="utf-8", newline="\n")

    if check:
        if stale:
            print("OUT OF DATE (run: python scripts/build.py):")
            for s in stale:
                print("  -", s)
            return 1
        print("build: up to date")
        return 0
    print("build: wrote" if stale else "build: nothing to do", *(f"\n  - {s}" for s in stale))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))

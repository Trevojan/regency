    p = found[key]
    aside = p.with_name(f"SKILL.denied-{today(day).isoformat()}.md")
    p.rename(aside)
    shutil.copyfile(bases[name], p)
    print(f"OK        engines: {key} denied; your text moved aside to {aside.name}; regency's base is back")
    return 0



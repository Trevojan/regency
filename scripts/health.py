def engines_ratify(repo, key, record=None, follow=None, machine=None, account=None, day=None):
    rec = load_record(record or default_record())
    if rec.get("_error"):
        print(f"FAIL      engines: the ratified record does not read ({rec['_error']}); fix it by hand, nothing is overwritten")
        return 2
    stamp = today(day).isoformat()
    if key == "repo":
        if follow not in ("regent", "project"):
            print("FAIL      engines: ratify repo needs --follow regent|project")
            return 2
        g = wire.guidelines_root(repo)
        own = g / ".sources" / "ENGINES.md" if g else None
        entry = {"follow": follow, "ratified": stamp}
        if follow == "project" and own and own.is_file():
            entry["sha256"] = sha(own)
        rec.setdefault("repos", {})[repo_key(repo)] = entry
    else:
        m, a = surfaces(machine, account)
        bases = regency_engines()
        found = {**copies_in("machine", m, bases), **copies_in("account", a, bases)}
        if key not in found:
            print(f"FAIL      engines: no copy named {key} reachable here")
            return 2
        rec.setdefault("copies", {})[key] = {"sha256": sha(found[key]), "ratified": stamp}
    save_record(record or default_record(), rec)
    print(f"AOK       engines: {key} ratified on {stamp}")
    return 0


def engines_restore(key, machine=None, day=None):
    surface, _, name = key.partition(":")
    if surface != "machine":
        print(f"INFO      engines: {key} lives on the account; regency cannot write there: put "
              f"{ENGINE_FILES}/<engine>.md back as that skill's SKILL.md on the account, or remove the skill")
        return 2
    m, _ = surfaces(machine, None)
    bases = regency_engines()
    found = copies_in("machine", m, bases)

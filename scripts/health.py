def run(cmd, cwd=None, timeout=120, stdin=None):
    return subprocess.run(cmd, cwd=cwd, input=stdin, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", timeout=timeout)


def shortcuts(rep, repo):
    if not wire.virtual_dir(repo):
        return rep.add("INFO", "shortcuts", "no .shortcuts/.virtual here: nothing to check")
    vp = run([sys.executable, str(HERE / "vp.py"), "check", "--from", str(repo)], cwd=repo)
    lines = [l for l in vp.stdout.splitlines() if l.strip()]
    for l in lines:
        if l.startswith(("UNRESOLVED", "MISSING")):
            rep.add("FAIL", "shortcuts", "virtual path " + " ".join(l.split()))
    rep.add("OK" if vp.returncode == 0 else "FAIL", "shortcuts", "virtual paths: " + (lines[-1] if lines else "no answer"))
    for verb, label, fix in (("check", "entry index", "shortcuts.py check"), ("drift", "drift", "shortcuts.py peek, then index")):
        r = run([sys.executable, str(HERE / "shortcuts.py"), verb, "--repo", str(repo)], cwd=repo)
        said = [l for l in r.stdout.splitlines() if l.strip()]
        if r.returncode == 0:
            rep.add("OK", "shortcuts", f"{label}: {said[-1] if said else 'no answer'}")
            continue
        for l in said[:-1][:5]:
            rep.add("WARN", "shortcuts", f"{label} " + " ".join(l.split()))
        rep.add("WARN", "shortcuts", f"{label}: {said[-1] if said else 'no answer'} -> {fix}")
    ix = run([sys.executable, str(HERE / "idx.py"), "--repo", str(repo), "check"], cwd=repo)
    rows = []
    for l in ix.stdout.splitlines():
        try:
            rows.append(json.loads(l))
        except ValueError:  # health: allow-silent idx.py answers in JSON lines; any other line is not an answer
            continue
    if ix.returncode == 2:
        err = next((r.get("error") for r in rows if r.get("error")), "no answer")
        return rep.add("WARN", "shortcuts", f"exact index: {err}")
    bad = [r for r in rows if r.get("status") in ("unresolved", "missing-file", "missing-node")]
    for r in bad:
        rep.add("FAIL", "shortcuts", f"index {r.get('status')}: {r.get('ref') or r.get('slice')}")
    cache = next((r for r in rows if r.get("check") == "cache"), {})
    drift = int(cache.get("drifted", 0)) + int(cache.get("deleted", 0))
    rep.add("WARN" if drift else "OK", "shortcuts",
            f"exact index: {cache.get('files', 0)} file(s), {cache.get('drifted', 0)} drifted, {cache.get('deleted', 0)} "
            f"deleted, {len(bad)} broken reference(s)" + ("; run idx.py build" if drift else ""))



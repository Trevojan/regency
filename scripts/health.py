def check_sets(repo):
    g = wire.guidelines_root(repo)
    d = g / HEALTH_DIR if g else None
    if not d or not d.is_dir():
        return []
    out = []
    for p in sorted(d.glob("*.json")):
        if p.name == "pipeline.json":
            continue
        try:
            out.append((p, json.loads(p.read_text(encoding="utf-8"))))
        except ValueError:
            out.append((p, None))
    return out


def appointment_ratify(repo, which, day=None):
    stamp, n = today(day).isoformat(), 0
    for p, body in check_sets(repo):
        if body is None or (which != "all" and body.get("part") != which):
            continue
        for t in body.get("topics", []):
            if not t.get("ratified"):
                t["ratified"] = stamp
                n += 1
        p.write_text(json.dumps(body, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"AOK       appointment: {n} topic(s) ratified on {stamp}")
    return 0


def run_topic(rep, repo, t):
    a = t.get("args") or {}
    c = t.get("check")
    if c == "names":
        root = Path(a["root"]) if a.get("root") else repo
        return names(rep, walk_entries(root, a.get("upload_set", False)), "files in the upload set" if a.get("upload_set") else "files")
    if c == "size":
        return size(rep, a.get("cap", 2_000_000), a.get("used"), repo)
    if c == "queues":
        return queues(rep, repo, a.get("file"), a.get("section"), a.get("days", 7), a.get("wip"))
    if c == "shortcuts":
        return shortcuts(rep, repo)
    if c == "version":
        return version(rep, repo)
    if c == "copies":
        return copies(rep, a.get("root") or ROOT, a.get("home"))
    if c == "distributable":
        return distributable(rep, repo, a.get("list"), a.get("release", []))
    if c == "engines":
        return engines(rep, repo, a.get("machine"), a.get("account"), a.get("record"))
    if c == "hooks":
        return hooks(rep, repo)
    if c == "context":
        return context(rep, a.get("budget"))
    if c == "pipeline":
        return pipeline(rep, repo, a.get("cases"), a.get("scan"), a.get("runs", True), a.get("scan_code", True))
    if c == "underuse":
        return underuse(rep, repo)
    if c == "command":
        try:
            r = run(a["run"], cwd=repo, timeout=a.get("timeout", 120))
        except (OSError, subprocess.TimeoutExpired) as e:
            return rep.add("FAIL", t.get("id", "command"), f"cannot run: {e}")
        return rep.add("OK" if r.returncode == a.get("exit", 0) else "FAIL", t.get("id", "command"),
                       f"exit {r.returncode}" + ("" if r.stdout.strip() else " (no output)"))
    return rep.add("FAIL", "project", f"topic {t.get('id')}: unknown check '{c}'")


def project(rep, repo):
    sets = check_sets(repo)
    if not sets:
        return rep.add("INFO", "project", "no check set yet: /regency:health:doctor assembles the project's caring topics")
    waiting = 0
    for p, body in sets:
        if body is None:
            rep.add("FAIL", "project", f"{p.name} does not parse")
            continue
        for t in body.get("topics", []):
            if t.get("ratified"):
                run_topic(rep, repo, t)
            else:
                waiting += 1
    if waiting:
        rep.add("INFO", "project", f"{waiting} topic(s) proposed, waiting for the Regent's ratification")


def harness(rep, plugin_root=ROOT):
    r = run([sys.executable, str(Path(plugin_root) / "scripts" / "doctor.py")], timeout=900)
    lines = [l for l in r.stdout.splitlines() if l.strip()]
    for l in lines:
        if l.startswith("FAIL"):
            rep.add("FAIL", "harness", l[4:].strip())
    rep.add("OK" if r.returncode == 0 else "FAIL", "harness", lines[-1] if lines else "doctor gave no answer")


def overview(repo, plugin_root=ROOT, machine=None, account=None, record=None):
    rows = []
    for label, fn in (("harness", lambda r: harness(r, plugin_root)), ("copies", lambda r: copies(r, plugin_root)),
                      ("version", lambda r: version(r, repo, plugin_root)), ("project", lambda r: project(r, repo)),
                      ("hooks", lambda r: hooks(r, repo, plugin_root)), ("context", lambda r: context(r, None, plugin_root)),
                      ("engines", lambda r: engines(r, repo, machine, account, record)), ("underuse", lambda r: underuse(r, repo))):
        sub = Report()
        try:
            fn(sub)
        except Exception as e:  # noqa: BLE001 - one broken check must not hide the others
            sub.add("FAIL", label, f"crashed: {type(e).__name__}: {e}")
        counts = {l: sum(1 for i in sub.items if i[0] == l) for l in LEVELS}
        tally = ", ".join(f"{n} {l.lower()}" for l, n in counts.items() if n and l not in ("OK", "INFO"))
        rows.append((sub.worst(), label, tally or "all clear"))
    rep = Report()
    for lvl, label, tally in rows:
        rep.add(lvl, label, tally + f" — /regency:health:{label}")
    return rep



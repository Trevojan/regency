def git(repo, *args):
    try:
        return run(["git", "-C", str(repo), *args], timeout=60)
    except (OSError, subprocess.TimeoutExpired):  # health: allow-silent the caller reports None as UNCHECKED
        return None


def distributable(rep, repo, listing=None, releases=()):
    st = git(repo, "status", "--porcelain")
    if st is None or st.returncode != 0:
        rep.add("UNCHECKED", "distributable", "not a git repository here: hand edits of generated files cannot be seen")
    else:
        edited = []
        for l in st.stdout.splitlines():
            path = l[3:].strip().strip('"')
            if l[:2].strip() in ("M", "MM", "AM", "RM") and (repo / path).is_file() and GENERATED_MARK.search(text_of(repo / path, 400)):
                edited.append(path)
        for p in edited:
            rep.add("FAIL", "distributable", f"{p} is generated and changed in the tree: edit its source, run the build (F4)")
        tracked = [l for l in (git(repo, "ls-files", "dist").stdout or "").splitlines() if l.strip()]
        if tracked:
            rep.add("WARN", "distributable", f"{len(tracked)} file(s) under dist/ are tracked by git: generated output is rebuilt, not kept")
        if not edited:
            rep.add("OK", "distributable", "no generated file changed by hand (F4)")
    if listing:
        bad = [d["path"] for d in load_listing(listing)
               if any(part in UPLOAD_SKIP_DIRS for part in Path(d["path"]).parts[:-1])
               or Path(d["path"]).suffix.lower() in ARCHIVES]
        for b in bad:
            rep.add("FAIL", "distributable", f"{b}: never uploaded (dist/, archives and generated files stay out)")
        if not bad:
            rep.add("OK", "distributable", "the uploaded set holds no dist/ output and no archive")
    for r in releases:
        r = Path(r) if Path(r).is_absolute() else repo / r
        hits = []
        for p in walk(r):
            if not is_text(p):
                continue
            for i, line in enumerate(text_of(p).splitlines(), 1):
                if re.search(r"[A-Za-z]:\\\\?Users\\|/home/[\w.-]+/|/Users/[\w.-]+/", line):
                    hits.append(f"{p.relative_to(r).as_posix()}:{i}")
        for h in hits:
            rep.add("WARN", "distributable", f"{h}: a machine path inside a release; releases run on their own paths (F5)")
        if not hits:
            rep.add("OK", "distributable", f"{r.name}: no machine path inside the release (F5)")



# ---------- report -----------------------------------------------------------------------------

class Report:
    def __init__(self):
        self.items = []

    def add(self, level, check, msg):
        self.items.append((level, check, msg))
        return level

    def extend(self, other):
        self.items.extend(other.items)

    def worst(self):
        for lvl in LEVELS:
            if any(i[0] == lvl for i in self.items):
                return lvl
        return "OK"

    def lines(self):
        order = {l: n for n, l in enumerate(LEVELS)}
        return [f"{lvl:<9} {chk}: {msg}" for lvl, chk, msg in sorted(self.items, key=lambda i: order[i[0]])]

    def code(self):
        return 1 if any(i[0] == "FAIL" for i in self.items) else 0


def today(arg=None):
    return dt.date.fromisoformat(arg) if arg else dt.date.today()


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def text_of(path, limit=None):
    try:
        data = Path(path).read_bytes()
    except OSError:  # health: allow-silent an unreadable file reads as empty; no check passes on what it cannot read
        return ""
    if limit:
        data = data[:limit]
    return data.decode("utf-8", "replace")


def is_text(path):
    try:
        chunk = Path(path).read_bytes()[:4096]
    except OSError:  # health: allow-silent an unreadable file is not text, so no check counts it as clean
        return False
    return b"\0" not in chunk


def repo_of(arg):
    return wire.repo_root(Path(arg).resolve() if arg else Path.cwd())


def walk(root, skip=WALK_SKIP):
    root = Path(root)
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part in skip for part in rel.parts[:-1]) or (p.is_dir() and p.name in skip):
            continue
        if p.is_file():
            yield p


def upload_set(root):
    """What the never-upload rule lets through: sources only, no dist/, archives, renderings or generated files."""
    for p in walk(root, WALK_SKIP | UPLOAD_SKIP_DIRS):
        rel = p.relative_to(root)
        if any(part in UPLOAD_SKIP_DIRS for part in rel.parts):
            continue
        if p.suffix.lower() in ARCHIVES + RENDERINGS or not is_text(p):
            continue
        if GENERATED_MARK.search(text_of(p, 400)):
            continue
        yield p


# ---------- names (R11.2) ----------------------------------------------------------------------

def load_listing(path):
    """A surface's file list: JSON (list of paths, or of {path, created_at?, sha256?, size?}, or a
    Projects project_info result with docs/files) or plain lines."""
    raw = Path(path).read_text(encoding="utf-8")
    try:
        data = json.loads(raw)
    except ValueError:
        return [{"path": l.strip()} for l in raw.splitlines() if l.strip()]
    if isinstance(data, dict):
        data = list(data.get("docs") or []) + list(data.get("files") or [])
    return [d if isinstance(d, dict) else {"path": str(d)} for d in data]


def parent_label(path, other):
    """The nearest parent folder name of `path` that differs from `other`'s at the same depth."""
    a, b = Path(path).parts[:-1], Path(other).parts[:-1]
    for i in range(1, len(a) + 1):
        mine = a[-i]
        theirs = b[-i] if i <= len(b) else None
        if mine != theirs:
            return mine.lstrip(".") or "root"
    return "root"


def names(rep, entries, label="files"):
    groups = {}
    for e in entries:
        name = Path(e["path"]).name
        stem = name.rsplit(".", 1)[0].lower() if "." in name[1:] else name.lower()
        if stem in IGNORED_STEMS:
            continue
        groups.setdefault(name.lower(), []).append(e)
    dup = fixed = 0
    for key, copies in sorted(groups.items()):
        if len(copies) < 2:
            continue
        # first = the earliest born; unknown dates last; on a tie the more specific (deeper) folder first,
        # so a loose copy never takes the name from the one in its part
        copies.sort(key=lambda e: (e.get("born") is None, str(e.get("born") or ""), -len(Path(e["path"]).parts), e["path"]))
        n = len(copies)
        if key in FIXED_NAMES:
            fixed += 1
            rep.add("INFO", "names", f"{Path(copies[0]['path']).name} ×{n}: fixed by its runtime; "
                                     "the folder tells them apart")
            continue
        dup += 1
        name = Path(copies[0]["path"]).name
        stem, dot, ext = name.rpartition(".") if "." in name[1:] else (name, "", "")
        suggests = ", ".join(f"{stem}{i}{dot}{ext}" for i in range(1, n + 1))
        hashes = {e.get("sha256") for e in copies}
        first = copies[0]["path"]
        if None not in hashes and len(hashes) == 1:
            others = "; ".join(e["path"] for e in copies[1:])
            rep.add("WARN", "names", f"{name} ×{n} (identical) — suggests {suggests}; candidate: {first} keeps "
                                     f"the name, {others} {'is a copy' if n == 2 else 'are copies'}: remove")
        else:
            def fate(e):
                if e.get("sha256") is None and len(Path(e["path"]).parts) == 1 < len(Path(first).parts):
                    return f"{e['path']} is loose at the root: likely a copy of {first} — compare, then remove"
                return f"{e['path']} → {parent_label(e['path'], first)}-{name}"
            renames = "; ".join(fate(e) for e in copies[1:])
            rep.add("WARN", "names", f"{name} ×{n} — suggests {suggests}; candidate: {first} keeps the name; "
                                     f"{renames}")
    level = "WARN" if dup else "OK"
    rep.add(level, "names", f"{dup} duplicate name(s) among {len(entries)} {label}; {fixed} fixed by a runtime "
                            "(README, CLAUDE and AGENTS not counted)")
    return dup


def walk_entries(root, uploads=False):
    root = Path(root)
    files = upload_set(root) if uploads else walk(root)
    out = []
    for p in files:
        st = p.stat()
        out.append({"path": p.relative_to(root).as_posix(), "born": dt.datetime.fromtimestamp(st.st_mtime).isoformat(),
                    "sha256": sha(p)})
    return out


def listing_entries(path):
    out = []
    for d in load_listing(path):
        out.append({"path": d["path"], "born": d.get("created_at") or d.get("born"), "sha256": d.get("sha256")})
    return out


# ---------- size -------------------------------------------------------------------------------

def size(rep, cap, used=None, root=None):
    method = "the surface's own figure"
    if used is None:
        files = list(upload_set(root))
        used = sum(p.stat().st_size for p in files)
        method = f"bytes of the {len(files)} text file(s) the upload rule lets through (an estimate of the surface's figure)"
    pct = 100.0 * used / cap if cap else 0.0
    level = "FAIL" if used > cap else "WARN" if pct >= 80 else "OK"
    rep.add(level, "size", f"{used:,} of {cap:,} B ({pct:.1f}%) — {method}")
    return used


# ---------- queues -----------------------------------------------------------------------------

def dated_section(text, section):
    """Top-level list items under the first heading that names `section`, up to the next heading of the same
    or a higher level. Each item: (first line, first YYYY-MM-DD on it or None)."""
    lines = text.replace("\r\n", "\n").split("\n")
    start, depth = None, 0
    for i, l in enumerate(lines):
        m = re.match(r"^(#{1,6})\s+(.*)$", l)
        if m and section.lower() in m.group(2).lower():
            start, depth = i + 1, len(m.group(1))
            break
    if start is None:
        return None
    items = []
    for l in lines[start:]:
        m = re.match(r"^(#{1,6})\s", l)
        if m and len(m.group(1)) <= depth:
            break
        if re.match(r"^[-*] ", l):
            d = DATE.search(l)
            items.append((l[2:].strip(), d.group(1) if d else None))
    return items


def queues(rep, repo, file=None, section=None, days=7, wip=None, day=None):
    now = today(day)
    if file:
        p = Path(file) if Path(file).is_absolute() else repo / file
        items = dated_section(text_of(p), section or "To apply") if p.is_file() else None
        if items is None:
            rep.add("WARN", "queues", f"{p.name}: no section '{section or 'To apply'}' to count")
        else:
            ages = [(now - dt.date.fromisoformat(d)).days for _, d in items if d]
            undated = [t for t, d in items if not d]
            old = [a for a in ages if a > days]
            level = "WARN" if old or undated else "OK"
            oldest = f"; oldest {max(ages)} day(s)" if ages else ""
            rep.add(level, "queues", f"{p.name} '{section or 'To apply'}': {len(old)} of {len(items)} item(s) older "
                                     f"than {days} day(s){oldest}" + (f"; {len(undated)} undated" if undated else ""))
    vdir = wire.virtual_dir(repo)
    led = vdir / "ongoing.json" if vdir else None
    if led and led.is_file():
        try:
            states = [i.get("state") for i in json.loads(led.read_text(encoding="utf-8")).get("items", [])]
        except ValueError:
            return rep.add("FAIL", "queues", "the ledger (ongoing.json) does not parse")
        review, draft = states.count("review"), states.count("draft")
        over = wip is not None and review > wip
        rep.add("WARN" if over else "OK", "queues",
                f"ledger: {review} in review" + (f" (WIP limit {wip})" if wip is not None else "") + f", {draft} draft(s), "
                f"{states.count('blocked')} blocked, {states.count('ongoing')} ongoing")
    elif not file:
        rep.add("INFO", "queues", "no ledger and no dated queue named: nothing to count")



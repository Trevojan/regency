def normalise(text, ignore):
    for pat in ignore:
        text = re.sub(pat, "<ignored>", text)
    return text.strip()


def watch_case(rep, repo, case):
    cid = case.get("id") or " ".join(case.get("run", []))
    expect = case.get("expect") or {}
    cwd = repo / case.get("cwd", ".")
    reach = set(expect.get("reach") or ["stdout", "stderr"])
    logs = [cwd / l for l in case.get("logs", [])]
    before = {l: (l.stat().st_size if l.is_file() else 0) for l in logs}

    def once():
        return run(case["run"], cwd=cwd, timeout=case.get("timeout", 60), stdin=case.get("stdin"))

    try:
        first = once()
    except FileNotFoundError as e:
        return rep.add("FAIL", "pipeline", f"{cid}: cannot run ({e.filename})")
    except subprocess.TimeoutExpired:
        return rep.add("FAIL", "pipeline", f"{cid}: no answer within {case.get('timeout', 60)} s")
    out, err = first.stdout.strip(), first.stderr.strip()
    want = expect.get("exit", 0)
    findings = 0
    if first.returncode != want:
        findings += 1
        if not out and not err:
            rep.add("FAIL", "pipeline", f"{cid}: silent error — exit {first.returncode} with no message at all")
        else:
            rep.add("FAIL", "pipeline", f"{cid}: exit {first.returncode}, expected {want}")
    seen = (out if "stdout" in reach else "") + (err if "stderr" in reach else "")
    hidden = (out if "stdout" not in reach else "") + (err if "stderr" not in reach else "")
    grew = [l.name for l in logs if l.is_file() and l.stat().st_size > before[l]]
    if (hidden or grew) and not seen:
        findings += 1
        where = " and ".join(([f"{'stderr' if err and 'stderr' not in reach else 'stdout'}"] if hidden else []) + grew)
        rep.add("WARN", "pipeline", f"{cid}: a readable message went to {where} only — nothing reaches the Regent "
                                    f"({'/'.join(sorted(reach))})")
    if expect.get("json"):
        try:
            json.loads(out)
        except ValueError:
            findings += 1
            rep.add("FAIL", "pipeline", f"{cid}: output is not JSON")
    if expect.get("stdout") and not re.search(expect["stdout"], out):
        findings += 1
        rep.add("FAIL", "pipeline", f"{cid}: output does not match /{expect['stdout']}/")
    if expect.get("stable", True):
        try:
            second = once()
        except (OSError, subprocess.TimeoutExpired):
            second = None
        if second is not None:
            ignore = case.get("ignore") or []
            a, b = normalise(first.stdout, ignore), normalise(second.stdout, ignore)
            if a != b:
                findings += 1
                ratio = difflib.SequenceMatcher(None, a, b).ratio()
                rep.add("WARN", "pipeline", f"{cid}: the same input gave two outputs — similarity {ratio:.2f} "
                                            "(declare volatile parts in 'ignore')")
    if not findings:
        rep.add("OK", "pipeline", f"{cid}: input -> process -> output holds")
    return findings


SILENT_BODY = (ast.Pass, ast.Continue)
SCAN_SUFFIXES = {".py", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".cs", ".java", ".go"}
EMPTY_CATCH = re.compile(r"catch\s*(\([^)]*\))?\s*\{\s*\}")
CATCH_NOOP = re.compile(r"\.catch\(\s*\(?\s*\w*\s*\)?\s*=>\s*(\{\s*\}|null|undefined)\s*\)")
GO_DROP = re.compile(r"if\s+err\s*!=\s*nil\s*\{\s*\}")


def silent_python(path, text):
    out = []
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return out
    lines = text.splitlines()

    def allowed(n):
        return 0 < n <= len(lines) and ALLOW_SILENT in lines[n - 1]

    for node in ast.walk(tree):
        if isinstance(node, ast.ExceptHandler):
            body = node.body
            silent = all(isinstance(b, SILENT_BODY) or (isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant))
                         or (isinstance(b, ast.Return) and (b.value is None or isinstance(b.value, ast.Constant)))
                         for b in body)
            if silent:
                what = "bare except" if node.type is None else "an exception"
                out.append((node.lineno, f"{what} swallowed: nothing logged, nothing raised", allowed(node.lineno)))
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            f = node.value.func
            name = f.attr if isinstance(f, ast.Attribute) else f.id if isinstance(f, ast.Name) else ""
            owner = f.value.id if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name) else ""
            checked = any(k.arg == "check" for k in node.value.keywords)
            if (owner == "subprocess" and name in ("run", "call") and not checked) or (owner == "os" and name == "system"):
                out.append((node.lineno, f"{owner}.{name}() result dropped: a failing process passes in silence",
                            allowed(node.lineno)))
    return out


def silent_other(path, text):
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        for pat, what in ((EMPTY_CATCH, "empty catch"), (CATCH_NOOP, "promise error dropped"), (GO_DROP, "error checked, then dropped")):
            if pat.search(line):
                out.append((i, f"{what}: nothing logged, nothing raised", ALLOW_SILENT in line))
    return out


def scan(rep, repo, paths=None):
    roots = [Path(p) if Path(p).is_absolute() else repo / p for p in (paths or ["."])]
    found = allowed = files = 0
    for r in roots:
        for p in ([r] if r.is_file() else walk(r)):
            if p.suffix.lower() not in SCAN_SUFFIXES or not is_text(p):
                continue
            files += 1
            text = text_of(p)
            hits = silent_python(p, text) if p.suffix == ".py" else silent_other(p, text)
            for line, msg, ok in hits:
                rel = wire.rel_posix(p, repo) or p.as_posix()
                if ok:
                    allowed += 1
                else:
                    found += 1
                    rep.add("WARN", "pipeline", f"{rel}:{line}: {msg} (mark it '# {ALLOW_SILENT} <why>' if it is meant)")
    rep.add("WARN" if found else "OK", "pipeline",
            f"silent-error scan: {found} finding(s) in {files} file(s); {allowed} declared silent on purpose")
    return found


def pipeline(rep, repo, cases=None, scan_paths=None, runs=True, scanning=True):
    g = wire.guidelines_root(repo)
    cf = Path(cases) if cases else (g / HEALTH_DIR / "pipeline.json" if g else None)
    if runs:
        if cf and cf.is_file():
            data = json.loads(cf.read_text(encoding="utf-8"))
            for c in data.get("cases", []):
                watch_case(rep, repo, c)
        else:
            rep.add("INFO", "pipeline", "no cases declared (.shortcuts/.health/pipeline.json): only the scan ran")
    if scanning:
        scan(rep, repo, scan_paths)



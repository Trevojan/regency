#!/usr/bin/env python3
"""shortcuts.py - the engine behind <guidelines>/.shortcuts/: one SQLite store and an honest entry index.

Decision record R7 (library/shortcuts.md). vp.py keeps the lineage and the work ledger; this script
keeps what a returning agent reads first: the entry index (.shortcuts/README.md) and the store that
says what changed since the last look.

Store: <guidelines>/.shortcuts/.virtual/shortcuts.db, gitignored (a cache any clone rebuilds).
  files   one row per fingerprinted file: sha256, bytes, mtime_ns, prev_sha256, at, session, source
  nodes   one row per heading or Glyph block of every guideline doc: stable id (the exact anchor,
          never the ordinal), parent, document order, line range, sha256 of the node's own lines
  meta    schema version and the migration record of fingerprints.json (schema 1)

Commands:
  index   [--doc FILE]   refresh the store: guideline docs, manifest targets, every recorded file
  record  FILE           fingerprint one file after a write (hook-lineage calls record())
  drift   [--count]      files changed outside the hooks since their last record, and which nodes moved
  check   [--count]      the entry index: pointers and anchors resolve, map <= 5 lines, no copied prose,
                         the generated state block is current
  refresh [--init|--hook]  rewrite the generated state block of .shortcuts/README.md (between the
                         shortcuts:state markers); --init appends the block once; --hook reads the hook
                         event on stdin, stays silent and never fails
  peek                   the entry index whole, the live state block, then check and drift counts
  migrate                import fingerprints.json (schema 1) into the store; the JSON file is kept
  export                 the store as JSON on stdout (schema 2), for reading and diffing
  --selftest             one planted defect per rule

Options: --repo DIR (default: the repository holding the current directory)

Adoption gate: nothing is written in a project without <guidelines>/.shortcuts/.virtual/.
Exit codes: 0 clean, 1 problems found (drift, check), 2 usage. Pure standard library, Python 3.8+.
"""
import json
import os
import re
import sqlite3
import subprocess
import sys
import tempfile
from collections import namedtuple
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hook_wire as wire  # noqa: E402

SCHEMA = 2
DB_NAME = "shortcuts.db"
LEGACY = "fingerprints.json"
IGNORED = ("shortcuts.db", "shortcuts.db-journal", "shortcuts.db-wal", "shortcuts.db-shm")
BEGIN = "<!-- shortcuts:state · generated by shortcuts.py refresh; never edit by hand -->"
BEGIN_TAG = "<!-- shortcuts:state"
END = "<!-- /shortcuts:state -->"
MAP_LIMIT = 5
COPY_MIN = 60            # characters: a shorter line is a label, not prose
SHOWN = 5                # ledger items listed per state in the block
POINTER = re.compile(r"\.(md|json|jsonl|py|xml|toml|ya?ml|cs|razor|ts|tsx|js|html|css|sql|txt|rs)$", re.I)
LEDGER_STATES = ("ongoing", "review", "blocked", "backlog")

DDL = """
CREATE TABLE IF NOT EXISTS meta  (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS files (path TEXT PRIMARY KEY, sha256 TEXT NOT NULL, bytes INTEGER NOT NULL,
                                  mtime_ns INTEGER NOT NULL, prev_sha256 TEXT, at TEXT NOT NULL,
                                  session TEXT, source TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS nodes (id TEXT PRIMARY KEY, doc TEXT NOT NULL, key TEXT NOT NULL,
                                  kind TEXT NOT NULL, level INTEGER, parent TEXT, ord INTEGER NOT NULL,
                                  line_start INTEGER NOT NULL, line_end INTEGER NOT NULL,
                                  sha256 TEXT NOT NULL, prev_sha256 TEXT, at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS nodes_by_doc ON nodes (doc, ord);
"""

Place = namedtuple("Place", "repo g vdir index db")
Node = namedtuple("Node", "id key text kind level parent ord start end sha")


# ---------- location ---------------------------------------------------------------------------

def locate(start=None):
    repo = wire.repo_root(Path(start) if start else Path(os.getcwd()))
    g = wire.guidelines_root(repo)
    vdir = wire.virtual_dir(repo)
    return Place(repo, g, vdir, (g / ".shortcuts" / "README.md") if g else None,
                 (vdir / DB_NAME) if vdir else None)


def skipped(rel_parts):
    return bool(wire.SKIP_PARTS.intersection(rel_parts)) or ".virtual" in rel_parts


def guideline_docs(place):
    if not place.g:
        return []
    out = []
    for p in sorted(place.g.rglob("*.md")):
        if p.is_file() and not skipped(p.relative_to(place.g).parts):
            out.append(p)
    return out


def g_rel(place, path):
    """Path relative to the guidelines root (the virtual_path form), or None."""
    try:
        return Path(path).resolve().relative_to(place.g.resolve()).as_posix()
    except (ValueError, OSError, AttributeError):
        return None


# ---------- store ------------------------------------------------------------------------------

def ensure_gitignore(vdir):
    gi = vdir / ".gitignore"
    have = gi.read_text(encoding="utf-8").splitlines() if gi.is_file() else []
    missing = [n for n in IGNORED if n not in have]
    if missing:
        wire.atomic_write(gi, "\n".join(have + missing) + "\n")


def open_db(place):
    if not place.vdir:
        return None
    ensure_gitignore(place.vdir)
    con = sqlite3.connect(str(place.db), timeout=5)
    con.executescript(DDL)
    con.execute("INSERT OR IGNORE INTO meta VALUES ('schema', ?)", (str(SCHEMA),))
    migrate_legacy(con, place)
    return con


def meta(con, key):
    row = con.execute("SELECT value FROM meta WHERE key = ?", (key,)).fetchone()
    return row[0] if row else None


def migrate_legacy(con, place):
    """Import fingerprints.json (schema 1) once. mtime_ns -1 forces a hash on the next drift."""
    legacy = place.vdir / LEGACY
    if meta(con, "migrated_from") or not legacy.is_file():
        return 0
    try:
        files = json.loads(legacy.read_text(encoding="utf-8")).get("files", {})
    except (ValueError, OSError) as e:
        con.execute("INSERT OR REPLACE INTO meta VALUES ('migrate_error', ?)", (f"{type(e).__name__}: {e}",))
        con.commit()
        return 0
    n = 0
    for rel, v in files.items():
        if isinstance(v, dict) and v.get("sha256"):
            n += con.execute("INSERT OR IGNORE INTO files VALUES (?, ?, ?, -1, NULL, ?, ?, 'import')",
                             (rel, v["sha256"], int(v.get("bytes", -1)), v.get("at") or wire.now(),
                              v.get("session"))).rowcount
    con.execute("INSERT OR REPLACE INTO meta VALUES ('migrated_from', ?)", (f"{LEGACY} schema 1, {n} file(s)",))
    con.execute("INSERT OR REPLACE INTO meta VALUES ('migrated_at', ?)", (wire.now(),))
    con.commit()
    return n


# ---------- nodes ------------------------------------------------------------------------------

def headings(lines):
    """Same rule as vp.py: a line opening with 1-6 '#' and a space."""
    for i, l in enumerate(lines):
        m = re.match(r"^(#{1,6})\s+(.*?)\s*$", l)
        if m:
            yield i, len(m.group(1)), m.group(2)


def anchor_key(text):
    """The exact anchor: the §name when the heading carries one, else the whole heading text."""
    sec = re.search(r"§([^\s—:]+)", text)
    return sec.group(1) if sec else text


def node_sha(lines, start, end):
    import hashlib
    return hashlib.sha256("\n".join(lines[start:end]).encode("utf-8")).hexdigest()


def parse_nodes(text, doc):
    """Every heading and Glyph block of one document, in document order.

    A heading node spans its own lines only (up to the next heading of any level), so a change in a
    child section never moves the parent's hash. A repeated key gets '~2', '~3': check reports it,
    because a citation resolves to the first one only.
    """
    lines = text.split("\n")
    heads = list(headings(lines))
    found, stack, seen = [], [], {}
    for k, (i, lvl, title) in enumerate(heads):
        end = heads[k + 1][0] if k + 1 < len(heads) else len(lines)
        key = anchor_key(title)
        seen[key] = seen.get(key, 0) + 1
        if seen[key] > 1:
            key = f"{key}~{seen[key]}"
        while stack and stack[-1][0] >= lvl:
            stack.pop()
        parent = stack[-1][1] if stack else None
        nid = f"{doc}#{key}"
        found.append((i, Node(nid, key, title, "heading", lvl, parent, 0, i, end, node_sha(lines, i, end))))
        stack.append((lvl, nid))
    for i, l in enumerate(lines):
        m = re.search(r"\[block'([^']+)'", l)
        if not m:
            continue
        end = next((j for j in range(i + 1, len(lines)) if lines[j].strip().startswith("[/block")), i) + 1
        key = m.group(1)
        seen[key] = seen.get(key, 0) + 1
        if seen[key] > 1:
            key = f"{key}~{seen[key]}"
        parent = next((n.id for li, n in reversed(found) if n.kind == "heading" and li <= i), None)
        found.append((i, Node(f"{doc}#{key}", key, m.group(1), "glyph_block", None, parent, 0, i, end,
                              node_sha(lines, i, end))))
    found.sort(key=lambda t: t[0])
    return [n._replace(ord=o) for o, (_, n) in enumerate(found)]


def index_doc(con, place, path):
    """Upsert one guideline doc's nodes; return the ids whose own lines changed (added included)."""
    doc = g_rel(place, path)
    text = Path(path).read_text(encoding="utf-8-sig", errors="replace")
    old = {r[0]: r[1] for r in con.execute("SELECT id, sha256 FROM nodes WHERE doc = ?", (doc,))}
    changed, at = [], wire.now()
    nodes = parse_nodes(text, doc)
    for n in nodes:
        prev = old.get(n.id)
        if prev != n.sha:
            changed.append(n.id)
        con.execute("INSERT OR REPLACE INTO nodes VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                    (n.id, doc, n.key, n.kind, n.level, n.parent, n.ord, n.start, n.end, n.sha,
                     prev if prev != n.sha else None, at))
    gone = set(old) - {n.id for n in nodes}
    for nid in gone:
        con.execute("DELETE FROM nodes WHERE id = ?", (nid,))
    return changed


# ---------- record / index ---------------------------------------------------------------------

def is_guideline_doc(place, path):
    rel = g_rel(place, path)
    return bool(rel) and rel.endswith(".md") and not skipped(Path(rel).parts)


def record(place, path, session=None, source="hook", con=None):
    """Fingerprint one file and, for a guideline doc, its nodes. Returns 'recorded', 'removed' or None."""
    path = Path(path)
    rel = wire.rel_posix(path, place.repo)
    if not place.vdir or not rel or wire.rel_posix(path, place.vdir) is not None or rel.startswith(".git/"):
        return None
    own = con is None
    con = con or open_db(place)
    try:
        if not path.is_file():
            con.execute("DELETE FROM files WHERE path = ?", (rel,))
            if place.g and g_rel(place, path):
                con.execute("DELETE FROM nodes WHERE doc = ?", (g_rel(place, path),))
            con.commit()
            return "removed"
        st = path.stat()
        sha = wire.sha256(path)
        row = con.execute("SELECT sha256 FROM files WHERE path = ?", (rel,)).fetchone()
        prev = row[0] if row and row[0] != sha else (None if not row else
                                                     con.execute("SELECT prev_sha256 FROM files WHERE path = ?",
                                                                 (rel,)).fetchone()[0])
        con.execute("INSERT OR REPLACE INTO files VALUES (?,?,?,?,?,?,?,?)",
                    (rel, sha, st.st_size, st.st_mtime_ns, prev, wire.now(), (session or "")[:8] or None, source))
        if is_guideline_doc(place, path):
            index_doc(con, place, path)
        con.commit()
        return "recorded"
    finally:
        if own:
            con.close()


def manifest_targets(place):
    return {t for e in wire.manifest_entries(place.vdir) for t in (e.get("refers_to") or [])}


def index_all(place, only=None):
    """Bring the store up to date. Unchanged size and mtime skip the hash. Returns (seen, recorded)."""
    con = open_db(place)
    try:
        if only:
            targets = [Path(only) if Path(only).is_absolute() else place.repo / only]
        else:
            known = {r[0] for r in con.execute("SELECT path FROM files")}
            targets = guideline_docs(place) + [place.repo / t for t in sorted(manifest_targets(place) | known)]
        seen, done = 0, 0
        for p in dict.fromkeys(targets):
            seen += 1
            rel = wire.rel_posix(p, place.repo)
            row = con.execute("SELECT bytes, mtime_ns FROM files WHERE path = ?", (rel,)).fetchone()
            if row and p.is_file():
                st = p.stat()
                if row == (st.st_size, st.st_mtime_ns):
                    continue
            if record(place, p, source="scan", con=con):
                done += 1
        return seen, done
    finally:
        con.close()


# ---------- drift ------------------------------------------------------------------------------

def node_moves(con, place, path):
    """Node ids of one guideline doc whose own lines differ from the store: changed, new, gone."""
    doc = g_rel(place, path)
    stored = {r[0]: r[1] for r in con.execute("SELECT id, sha256 FROM nodes WHERE doc = ?", (doc,))}
    live = {n.id: n.sha for n in parse_nodes(Path(path).read_text(encoding="utf-8-sig", errors="replace"), doc)}
    out = [f"{i} (changed)" for i in live if i in stored and stored[i] != live[i]]
    out += [f"{i} (new)" for i in live if i not in stored]
    out += [f"{i} (gone)" for i in stored if i not in live]
    return out


def drift(place, hashing=True):
    """[(kind, rel, detail)] — kind: drift (content changed), gone, unindexed, maybe (stat only)."""
    if not place.vdir:
        return []
    con = open_db(place)
    try:
        out = []
        for rel, sha, size, mtime in con.execute("SELECT path, sha256, bytes, mtime_ns FROM files ORDER BY path"):
            p = place.repo / rel
            if not p.is_file():
                out.append(("gone", rel, ""))
                continue
            st = p.stat()
            if (st.st_size, st.st_mtime_ns) == (size, mtime):
                continue
            if not hashing:
                out.append(("maybe", rel, ""))
                continue
            if wire.sha256(p) != sha:
                moves = node_moves(con, place, p) if is_guideline_doc(place, p) else []
                out.append(("drift", rel, "; ".join(moves[:6]) + (f"; +{len(moves) - 6}" if len(moves) > 6 else "")))
        known = {r[0] for r in con.execute("SELECT path FROM files")}
        for p in guideline_docs(place):
            rel = wire.rel_posix(p, place.repo)
            if rel not in known:
                out.append(("unindexed", rel, ""))
        return out
    finally:
        con.close()


# ---------- the generated state block ----------------------------------------------------------

def git(repo, *args):
    try:
        r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=5)
        return r.stdout.strip() if r.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def version_of(repo):
    v = repo / "VERSION"
    if v.is_file():
        first = v.read_text(encoding="utf-8", errors="replace").strip().splitlines()
        if first:
            return first[0].strip()
    plugin = repo / ".claude-plugin" / "plugin.json"
    if plugin.is_file():
        try:
            return str(json.loads(plugin.read_text(encoding="utf-8")).get("version") or "—")
        except ValueError:
            pass
    return git(repo, "describe", "--tags", "--abbrev=0") or "—"


def ledger(place):
    led = place.vdir / "ongoing.json" if place.vdir else None
    if not led or not led.is_file():
        return None
    try:
        return json.loads(led.read_text(encoding="utf-8-sig"))
    except ValueError:
        return {"unreadable": True}


def last_checkpoint(place):
    cp = place.vdir / "checkpoints.jsonl" if place.vdir else None
    if not cp or not cp.is_file():
        return None
    for line in reversed(cp.read_text(encoding="utf-8", errors="replace").splitlines()):
        try:
            c = json.loads(line)
        except ValueError:
            continue
        what = c.get("gen_ai.tool.name") or c.get("regency.event") or "?"
        unit = f" ({c['regency.unit']})" if c.get("regency.unit") else ""
        return f"{c.get('ts', '?')} {what} {c.get('regency.target', '')}{unit}".strip()
    return None


def stale_count(place):
    return sum(p.read_text(encoding="utf-8-sig", errors="replace").count(wire.STALE_MARK)
               for p in guideline_docs(place))


def latest_order(place):
    od = place.g / ".orders" if place.g else None
    nums = sorted(p.name for p in od.glob("ORD-*") if re.match(r"^ORD-\d{4,}$", p.name)) if od and od.is_dir() else []
    return nums[-1] if nums else "—"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render_state(place, nl="\n"):
    """The block between the markers. Deterministic: no clock, no commit hash (a commit of the block
    would change the hash it shows)."""
    rows = [("branch", git(place.repo, "branch", "--show-current") or "—"), ("version", version_of(place.repo))]
    led = ledger(place)
    if led is None:
        rows.append(("ledger", "absent"))
    elif led.get("unreadable"):
        rows.append(("ledger", "UNREADABLE (vp.py ongoing)"))
    else:
        items = [it for it in led.get("items", []) if isinstance(it, dict)]
        by = {s: [it for it in items if it.get("state") == s] for s in LEDGER_STATES}
        rows.append(("ledger", " / ".join(f"{len(by[s])} {s}" for s in LEDGER_STATES)
                     + f" (updated {led.get('updated') or '?'})"))
        for it in by["ongoing"][:SHOWN]:
            rows.append(("ongoing", f"{it.get('id')} {it.get('title', '')}"
                         + (f" → {it['next']}" if it.get("next") else "")))
        for it in by["review"][:SHOWN]:
            rows.append(("review", f"{it.get('id')} {it.get('title', '')}"))
        for it in by["blocked"][:SHOWN]:
            rows.append(("blocked", f"{it.get('id')} ← {it.get('blocked_by', '?')}"))
    rows.append(("last checkpoint", last_checkpoint(place) or "—"))
    rows.append(("STALE", stale_count(place)))
    rows.append(("latest Order", latest_order(place)))
    body = [BEGIN, "| state | value |", "|---|---|"] + [f"| {cell(k)} | {cell(v)} |" for k, v in rows] + [END]
    return nl.join(body)


def find_block(text):
    """(start, end) character span of the whole block, markers included; None when absent.
    Raises ValueError when the markers are broken (one without the other, or out of order)."""
    b, e = text.find(BEGIN_TAG), text.find(END)
    if b < 0 and e < 0:
        return None
    if b < 0 or e < 0 or e < b or text.find(BEGIN_TAG, b + 1) >= 0:
        raise ValueError("shortcuts:state markers are broken (one missing, repeated or out of order)")
    return b, e + len(END)


def refresh(place, init=False):
    """'written', 'same', 'no-block', 'no-index', 'no-virtual' or 'broken'."""
    if not place.vdir:
        return "no-virtual"
    if not place.index or not place.index.is_file():
        return "no-index"
    raw = place.index.read_bytes().decode("utf-8-sig", errors="replace")
    nl = "\r\n" if "\r\n" in raw else "\n"
    block = render_state(place, nl)
    try:
        span = find_block(raw)
    except ValueError:
        return "broken"
    if span is None:
        if not init:
            return "no-block"
        new = raw.rstrip("\r\n") + nl + nl + block + nl
    else:
        if raw[span[0]:span[1]] == block:
            return "same"
        new = raw[:span[0]] + block + raw[span[1]:]
    wire.atomic_write(place.index, new)
    record(place, place.index, source="refresh")
    return "written"


# ---------- check ------------------------------------------------------------------------------

def strip_block(text):
    try:
        span = find_block(text)
    except ValueError:
        return text
    return text if span is None else text[:span[0]] + text[span[1]:]


def pointers(text):
    """Targets the index points at: markdown link targets and backticked paths (no spaces, no holes).
    A ⟨…⟩ hole is still unfilled, so nothing inside it is a pointer yet."""
    text = re.sub(r"⟨[^⟩]*⟩", "", text)
    out = []
    for m in re.finditer(r"\[[^\]]*\]\(([^)\s]+)\)", text):
        out.append(m.group(1))
    for m in re.finditer(r"`([^`\s]+)`", text):
        t = m.group(1)
        if ("/" in t or POINTER.search(t.split("#")[0])) and not re.search(r"[<>⟨⟩*${}]", t):
            out.append(t)
    keep = []
    for t in out:
        if re.match(r"^(https?:|mailto:|#)", t) or t.startswith("/regency"):
            continue
        keep.append(t)
    return list(dict.fromkeys(keep))


def resolve_pointer(place, target):
    """(ok, why) for one pointer: the file exists under the index folder, the guidelines root or the
    repository; an anchor must name a node of that file."""
    file_part, _, anchor = target.partition("#")
    file_part = file_part[2:] if file_part.startswith("./") else file_part
    bases = [place.index.parent, place.g, place.repo]
    hit = next((b / file_part for b in bases if (b / file_part).exists()), None)
    if hit is None:
        return False, "dead pointer"
    if anchor and hit.is_file() and hit.suffix.lower() == ".md":
        nodes = parse_nodes(hit.read_text(encoding="utf-8-sig", errors="replace"), "")
        if anchor not in {n.key for n in nodes} | {n.text for n in nodes}:
            return False, "dead anchor"
    return True, ""


def map_lines(text):
    lines = text.split("\n")
    for i, lvl, title in headings(lines):
        if re.search(r"(?i)\bmapa?\b", title):
            n = 0
            for l in lines[i + 1:]:
                if re.match(r"^#{1,6}\s", l):
                    break
                if l.strip() and not l.lstrip().startswith(">"):  # a blockquote is guidance, not the map
                    n += 1
            return n
    return None


def norm(line):
    return re.sub(r"\s+", " ", line.strip().strip("|").strip())


def check(place):
    """[(kind, detail)] for the entry index. Empty list = clean."""
    if not place.g:
        return [("index", "no guidelines root (library/layouts.md §1)")]
    if not place.index or not place.index.is_file():
        return [("index", ".shortcuts/README.md is missing")]
    raw = place.index.read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n")
    body = strip_block(raw)
    out = []
    for t in pointers(body):
        ok, why = resolve_pointer(place, t)
        if not ok:
            out.append(({"dead pointer": "dead", "dead anchor": "anchor"}[why], f"{t}: {why}"))
    n = map_lines(body)
    if n is not None and n > MAP_LIMIT:
        out.append(("map", f"the map has {n} lines; the limit is {MAP_LIMIT} (what does not fit is a document)"))
    own = {}
    for p in guideline_docs(place):
        if p.resolve() == place.index.resolve():
            continue
        for l in p.read_text(encoding="utf-8-sig", errors="replace").split("\n"):
            k = norm(l)
            if len(k) >= COPY_MIN and not k.startswith("#"):
                own.setdefault(k, g_rel(place, p))
    for l in body.split("\n"):
        k = norm(l)
        if len(k) >= COPY_MIN and k in own:
            out.append(("copy", f"{own[k]}: the index copies a line of it; point to it instead: {k}"))
    for doc_nodes in [parse_nodes(raw, "README.md")]:
        dups = [n.key for n in doc_nodes if "~" in n.key]
        out += [("anchor", f"README.md#{d}: repeated heading; a citation resolves to the first only") for d in dups]
    try:
        span = find_block(raw)
    except ValueError as e:
        out.append(("state", str(e)))
        span = False
    if span is None:
        out.append(("state", "no generated state block: shortcuts.py refresh --init"))
    elif span:
        if raw[span[0]:span[1]] != render_state(place):
            out.append(("state", "state block out of date: shortcuts.py refresh"))
    return out


# ---------- guard (hook-acts-guard calls this) -------------------------------------------------

def guard_generated(event, place=None):
    """A reason to deny when a write would hand-edit the generated block of the entry index; else None."""
    path = wire.target_path(event)
    if not path or event.get("tool_name") not in ("Edit", "MultiEdit", "Write"):
        return None
    place = place or locate(path.parent)
    if not place.index or not place.index.is_file() or path.resolve() != place.index.resolve():
        return None
    text = place.index.read_text(encoding="utf-8-sig", errors="replace")
    try:
        span = find_block(text)
    except ValueError:
        return None
    ti = wire.tool_input(event)
    reason = (".shortcuts/README.md: the shortcuts:state block is generated; never edit it by hand (F4): "
              "run shortcuts.py refresh")
    if event.get("tool_name") == "Write":
        new = ti.get("content") or ""
        try:
            new_span = find_block(new)
        except ValueError:
            return reason
        old_block = text[span[0]:span[1]] if span else None
        new_block = new[new_span[0]:new_span[1]] if new_span else None
        return reason if old_block != new_block and span is not None else None
    edits = ti.get("edits") if event.get("tool_name") == "MultiEdit" else [ti]
    for ed in edits or []:
        old, new = (ed or {}).get("old_string") or "", (ed or {}).get("new_string") or ""
        if BEGIN_TAG in old or END in old or BEGIN_TAG in new or END in new:
            return reason
        if span and old:
            at = text.find(old)
            if at >= 0 and at < span[1] and at + len(old) > span[0]:
                return reason
    return None


# ---------- summaries --------------------------------------------------------------------------

def summary_part(place):
    """One fragment for the SessionStart resume line (hook-resume), or None outside adopted projects."""
    if not place.vdir:
        return None
    c, d = check(place), [x for x in drift(place) if x[0] in ("drift", "gone")]
    return f"shortcuts check {len(c)} · drift {len(d)}" + (" (shortcuts.py peek)" if c or d else "")


def peek(place):
    lines = []
    if place.index and place.index.is_file():
        raw = place.index.read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n")
        lines.append(raw.rstrip("\n"))
        try:
            span = find_block(raw)
        except ValueError:
            span = None
        if not span or raw[span[0]:span[1]] != render_state(place):
            lines += ["", "--- state (live; the block above is absent or out of date) ---", render_state(place)]
    else:
        lines.append("no entry index (.shortcuts/README.md)")
        if place.vdir:
            lines += ["", render_state(place)]
    c = check(place)
    d = drift(place) if place.vdir else []
    lines += ["", f"check: {len(c)} problem(s)"] + [f"  {k:8} {v}" for k, v in c[:10]]
    lines += [f"drift: {len(d)}"] + [f"  {k:9} {r}  {x}".rstrip() for k, r, x in d[:10]]
    lines.append("ledger detail: vp.py ongoing · traces: vp.py trace")
    return "\n".join(lines)


def export(place):
    con = open_db(place)
    try:
        files = {r[0]: dict(zip(("sha256", "bytes", "mtime_ns", "prev_sha256", "at", "session", "source"), r[1:]))
                 for r in con.execute("SELECT * FROM files ORDER BY path")}
        nodes = {r[0]: dict(zip(("doc", "key", "kind", "level", "parent", "ord", "line_start", "line_end",
                                 "sha256", "prev_sha256", "at"), r[1:]))
                 for r in con.execute("SELECT * FROM nodes ORDER BY doc, ord")}
        return {"schema": SCHEMA, "meta": dict(con.execute("SELECT key, value FROM meta").fetchall()),
                "files": files, "nodes": nodes}
    finally:
        con.close()



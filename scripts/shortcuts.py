#!/usr/bin/env python3
"""shortcuts.py - the engine behind <guidelines>/.shortcuts/: an honest entry index and what changed since the last look.

Decision records R7 and R12 (library/shortcuts.md). vp.py keeps the lineage and the work ledger; idx.py keeps
the exact index. This script keeps what a returning agent reads first: the entry index (.shortcuts/README.md),
its generated state block, and the file fingerprints that say what changed outside the hooks. It has no store of
its own: everything lives in idx.py's <virtual>/index.sqlite (the prints table, beside idx's nodes), a cache
gitignored beside itself that any clone rebuilds.

Commands:
  index   [--doc FILE]   refresh the fingerprints of the guideline docs, the manifest targets and every recorded
                         file (size and mtime unchanged skip the hash) and re-index what moved; builds the exact
                         index (guidelines only) when there is none
  record  FILE           fingerprint one file after a write (hook-lineage calls record())
  drift   [--count]      files changed outside the hooks since their last record, and which nodes moved
  check   [--count]      the entry index: pointers and anchors resolve, map <= 5 lines, no copied prose, no
                         repeated heading, the generated state block is current
  refresh [--init|--hook]  rewrite the generated state block of .shortcuts/README.md (between the
                         shortcuts:state markers); --init appends the block once; --hook reads the hook event on
                         stdin, stays silent and never fails
  peek                   the entry index whole, the live state block, then check and drift counts
  migrate                import fingerprints.json (schema 1, regency 2.11 and earlier) into the prints table, once
  export                 the prints and the store's meta as JSON on stdout, for reading and diffing
  --selftest             one planted defect per rule

Options: --repo DIR (default: the repository holding the current directory)

Adoption gate: nothing is written in a project without <guidelines>/.shortcuts/.virtual/.
Exit codes: 0 clean, 1 problems found (drift, check), 2 usage. Pure standard library, Python 3.8+.
"""
import json
import os
import re
import sqlite3
import subprocess
import sys
import tempfile
from collections import namedtuple
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hook_wire as wire  # noqa: E402
import idx  # noqa: E402  (the one store: connect(), parse(), update(), build())

LEGACY = "fingerprints.json"
BEGIN = "<!-- shortcuts:state · generated by shortcuts.py refresh; never edit by hand -->"
BEGIN_TAG = "<!-- shortcuts:state"
END = "<!-- /shortcuts:state -->"
MAP_LIMIT = 5
COPY_MIN = 60            # characters: a shorter line is a label, not prose
SHOWN = 5                # ledger items listed per state in the block
POINTER = re.compile(r"\.(md|json|jsonl|py|xml|toml|ya?ml|cs|razor|ts|tsx|js|html|css|sql|txt|rs)$", re.I)
LEDGER_STATES = ("ongoing", "draft", "review", "blocked", "backlog")

Place = namedtuple("Place", "repo g vdir index")


# ---------- location ---------------------------------------------------------------------------

def locate(start=None):
    repo = wire.repo_root(Path(start) if start else Path(os.getcwd()))
    g = wire.guidelines_root(repo)
    vdir = wire.virtual_dir(repo)
    return Place(repo, g, vdir, (g / ".shortcuts" / "README.md") if g else None)


def skipped(rel_parts):
    return bool(wire.SKIP_PARTS.intersection(rel_parts)) or ".virtual" in rel_parts


def guideline_docs(place):
    if not place.g:
        return []
    return [p for p in sorted(place.g.rglob("*.md")) if p.is_file() and not skipped(p.relative_to(place.g).parts)]


def g_rel(place, path):
    """Path relative to the guidelines root (the virtual_path form), or None."""
    try:
        return Path(path).resolve().relative_to(place.g.resolve()).as_posix()
    except (ValueError, OSError, AttributeError):
        return None


def is_guideline_doc(place, path):
    rel = g_rel(place, path)
    return bool(rel) and rel.endswith(".md") and not skipped(Path(rel).parts)


# ---------- the store (idx.py's) ---------------------------------------------------------------

def open_db(place, create=True):
    """idx.py's index.sqlite; the legacy fingerprints.json is imported once. Writers create the store (and the
    .gitignore beside it); readers (drift, export, health) pass create=False and never add a file to the project."""
    if not place.vdir:
        return None
    con = idx.connect(place.vdir, create=create)
    if con is not None:
        migrate_legacy(con, place)
    return con


def meta(con, key):
    row = con.execute("SELECT v FROM meta WHERE k = ?", (key,)).fetchone()
    return row[0] if row else None


def migrate_legacy(con, place):
    """Import fingerprints.json (schema 1) once. mtime_ns -1 forces a hash on the next drift or index."""
    legacy = place.vdir / LEGACY
    if meta(con, "prints_migrated_from") or not legacy.is_file():
        return 0
    try:
        files = json.loads(legacy.read_text(encoding="utf-8")).get("files", {})
    except (ValueError, OSError) as e:
        con.execute("INSERT OR REPLACE INTO meta VALUES ('prints_migrate_error', ?)", (f"{type(e).__name__}: {e}",))
        con.commit()
        return 0
    n = 0
    for rel, v in files.items():
        if isinstance(v, dict) and v.get("sha256"):
            n += con.execute("INSERT OR IGNORE INTO prints VALUES (?, ?, ?, -1, NULL, ?, ?, 'import')",
                             (rel, v["sha256"], int(v.get("bytes", -1)), v.get("at") or wire.now(),
                              v.get("session"))).rowcount
    con.execute("INSERT OR REPLACE INTO meta VALUES ('prints_migrated_from', ?)", (f"{LEGACY} schema 1, {n} file(s)",))
    con.execute("INSERT OR REPLACE INTO meta VALUES ('prints_migrated_at', ?)", (wire.now(),))
    con.commit()
    return n




def record(place, path, session=None, source="hook", con=None):
    """Fingerprint one file. Returns 'recorded', 'removed' or None (outside the project, in .virtual or .git)."""
    path = Path(path)
    rel = wire.rel_posix(path, place.repo)
    if not place.vdir or not rel or wire.rel_posix(path, place.vdir) is not None or rel.startswith(".git/"):
        return None
    own = con is None
    con = con or open_db(place)
    try:
        if not path.is_file():
            con.execute("DELETE FROM prints WHERE path = ?", (rel,))
            con.commit()
            return "removed"
        st = path.stat()
        sha = wire.sha256(path)
        row = con.execute("SELECT sha256, prev_sha256 FROM prints WHERE path = ?", (rel,)).fetchone()
        prev = (row[0] if row[0] != sha else row[1]) if row else None
        con.execute("INSERT OR REPLACE INTO prints VALUES (?,?,?,?,?,?,?,?)",
                    (rel, sha, st.st_size, st.st_mtime_ns, prev, wire.now(), (session or "")[:8] or None, source))
        con.commit()
        return "recorded"
    finally:
        if own:
            con.close()


def manifest_targets(place):
    return {wire.ref_path(t) for e in wire.manifest_entries(place.vdir) for t in (e.get("refers_to") or [])}


def index_all(place, only=None):
    """Bring the prints up to date, and the exact index for what moved. Returns (seen, recorded)."""
    con = open_db(place)
    try:
        if not idx.built(con):
            con.close()
            idx.build(place.repo, place.vdir, guidelines_only=True)
            con = open_db(place)
        g_rel_root = wire.rel_posix(place.g, place.repo) or ""
        if only:
            targets = [Path(only) if Path(only).is_absolute() else place.repo / only]
        else:
            known = {r[0] for r in con.execute("SELECT path FROM prints")}
            targets = guideline_docs(place) + [place.repo / t for t in sorted(manifest_targets(place) | known)]
        seen, done = 0, 0
        for p in dict.fromkeys(targets):
            seen += 1
            rel = wire.rel_posix(p, place.repo)
            row = con.execute("SELECT bytes, mtime_ns FROM prints WHERE path = ?", (rel,)).fetchone()
            if row and p.is_file() and tuple(row) == (p.stat().st_size, p.stat().st_mtime_ns):
                continue
            if record(place, p, source="scan", con=con):
                done += 1
                if p.is_file() and rel:
                    with con:
                        idx.update(con, place.repo, rel, g_rel_root)
        return seen, done
    finally:
        con.close()


# ---------- drift ------------------------------------------------------------------------------

def node_moves(con, place, path):
    """Section labels of one doc whose text differs from the exact index: changed (the deepest only), new, gone."""
    rel = wire.rel_posix(path, place.repo)
    stored = {r["id"]: (r["label"], r["exact"]) for r in con.execute(
        "SELECT id, label, exact FROM nodes WHERE path = ? AND kind = 'section'", (rel,))}
    if not stored:
        return []
    nodes = [nd for nd in idx.parse(rel, Path(path).read_bytes())[0] if nd["kind"] == "section"]
    live = {nd["id"]: (nd["label"], nd["exact"]) for nd in nodes}
    changed = {i for i in live if i in stored and stored[i][1] != live[i][1]}
    holders = {nd["parent_id"] for nd in nodes if nd["id"] in changed}   # a parent changes with its child
    out = [f"#{live[i][0]} (changed)" for i in live if i in changed and i not in holders]
    out += [f"#{live[i][0]} (new)" for i in live if i not in stored]
    out += [f"#{stored[i][0]} (gone)" for i in stored if i not in live]
    return out


def drift(place, hashing=True):
    """[(kind, rel, detail)] — kind: drift (content changed), gone, unindexed, maybe (stat only), store (none yet)."""
    if not place.vdir:
        return []
    con = open_db(place, create=False)
    if con is None:
        return [("store", "", "no store yet: shortcuts.py index")]
    try:
        out = []
        for rel, sha, size, mtime in con.execute("SELECT path, sha256, bytes, mtime_ns FROM prints ORDER BY path"):
            p = place.repo / rel
            if not p.is_file():
                out.append(("gone", rel, ""))
                continue
            st = p.stat()
            if (st.st_size, st.st_mtime_ns) == (size, mtime):
                continue
            if not hashing:
                out.append(("maybe", rel, ""))
                continue
            if wire.sha256(p) != sha:
                moves = node_moves(con, place, p) if is_guideline_doc(place, p) else []
                out.append(("drift", rel, "; ".join(moves[:6]) + (f"; +{len(moves) - 6}" if len(moves) > 6 else "")))
        known = {r[0] for r in con.execute("SELECT path FROM prints")}
        for p in guideline_docs(place):
            rel = wire.rel_posix(p, place.repo)
            if rel not in known:
                out.append(("unindexed", rel, ""))
        return out
    finally:
        con.close()


# ---------- the generated state block ----------------------------------------------------------

def git(repo, *args):
    try:
        r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=5)
        return r.stdout.strip() if r.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def version_of(repo):
    v = repo / "VERSION"
    if v.is_file():
        first = v.read_text(encoding="utf-8", errors="replace").strip().splitlines()
        if first:
            return first[0].strip()
    plugin = repo / ".claude-plugin" / "plugin.json"
    if plugin.is_file():
        try:
            return str(json.loads(plugin.read_text(encoding="utf-8")).get("version") or "—")
        except ValueError:
            pass
    return git(repo, "describe", "--tags", "--abbrev=0") or "—"


def regency_of(place):
    """The regency version the project's stamp records (migrate.py), or '—'."""
    p = place.g / ".shortcuts" / "regency.json" if place.g else None
    try:
        return str(json.loads(p.read_text(encoding="utf-8-sig")).get("regency") or "—") if p and p.is_file() else "—"
    except ValueError:
        return "unreadable"


def ledger(place):
    led = place.vdir / "ongoing.json" if place.vdir else None
    if not led or not led.is_file():
        return None
    try:
        return json.loads(led.read_text(encoding="utf-8-sig"))
    except ValueError:
        return {"unreadable": True}


def last_checkpoint(place):
    cp = place.vdir / "checkpoints.jsonl" if place.vdir else None
    if not cp or not cp.is_file():
        return None
    for line in reversed(cp.read_text(encoding="utf-8", errors="replace").splitlines()):
        try:
            c = json.loads(line)
        except ValueError:
            continue
        what = c.get("gen_ai.tool.name") or c.get("regency.event") or "?"
        unit = f" ({c['regency.unit']})" if c.get("regency.unit") else ""
        return f"{c.get('ts', '?')} {what} {c.get('regency.target', '')}{unit}".strip()
    return None


def stale_count(place):
    return sum(p.read_text(encoding="utf-8-sig", errors="replace").count(wire.STALE_MARK)
               for p in guideline_docs(place))


def latest_order(place):
    od = place.g / ".orders" if place.g else None
    nums = sorted(p.name for p in od.glob("ORD-*") if re.match(r"^ORD-\d{4,}$", p.name)) if od and od.is_dir() else []
    return nums[-1] if nums else "—"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render_state(place, nl="\n"):
    """The block between the markers. Deterministic: no clock, no commit hash (a commit of the block would
    change the hash it shows)."""
    rows = [("branch", git(place.repo, "branch", "--show-current") or "—"), ("version", version_of(place.repo)),
            ("regency", regency_of(place))]
    led = ledger(place)
    if led is None:
        rows.append(("ledger", "absent"))
    elif led.get("unreadable"):
        rows.append(("ledger", "UNREADABLE (vp.py ongoing)"))
    else:
        items = [it for it in led.get("items", []) if isinstance(it, dict)]
        by = {s: [it for it in items if it.get("state") == s] for s in LEDGER_STATES}
        rows.append(("ledger", " / ".join(f"{len(by[s])} {s}" for s in LEDGER_STATES)
                     + f" (updated {led.get('updated') or '—'})"))
        for it in by["ongoing"][:SHOWN]:
            rows.append(("ongoing", f"{it.get('id')} {it.get('title', '')}" + (f" → {it['next']}" if it.get("next") else "")))
        for it in by["draft"][:SHOWN]:
            rows.append(("draft", f"{it.get('id')} {it.get('title', '')} (UNVERIFIED)"))
        for it in by["review"][:SHOWN]:
            rows.append(("review", f"{it.get('id')} {it.get('title', '')}"))
        for it in by["blocked"][:SHOWN]:
            rows.append(("blocked", f"{it.get('id')} ← {it.get('blocked_by', '?')}"))
    rows.append(("last checkpoint", last_checkpoint(place) or "—"))
    rows.append(("STALE", stale_count(place)))
    rows.append(("latest Order", latest_order(place)))
    body = [BEGIN, "| state | value |", "|---|---|"] + [f"| {cell(k)} | {cell(v)} |" for k, v in rows] + [END]
    return nl.join(body)


def find_block(text):
    """(start, end) character span of the whole block, markers included; None when absent.
    Raises ValueError when the markers are broken (one without the other, repeated, or out of order)."""
    b, e = text.find(BEGIN_TAG), text.find(END)
    if b < 0 and e < 0:
        return None
    if b < 0 or e < 0 or e < b or text.find(BEGIN_TAG, b + 1) >= 0:
        raise ValueError("shortcuts:state markers are broken (one missing, repeated or out of order)")
    return b, e + len(END)


def refresh(place, init=False):
    """'written', 'same', 'no-block', 'no-index', 'no-virtual' or 'broken'."""
    if not place.vdir:
        return "no-virtual"
    if not place.index or not place.index.is_file():
        return "no-index"
    raw = place.index.read_bytes().decode("utf-8-sig", errors="replace")
    nl = "\r\n" if "\r\n" in raw else "\n"
    block = render_state(place, nl)
    try:
        span = find_block(raw)
    except ValueError:
        return "broken"
    if span is None:
        if not init:
            return "no-block"
        new = raw.rstrip("\r\n") + nl + nl + block + nl
    else:
        if raw[span[0]:span[1]] == block:
            return "same"
        new = raw[:span[0]] + block + raw[span[1]:]
    wire.atomic_write(place.index, new)
    record(place, place.index, source="refresh")
    idx.update_hook(place.vdir, place.repo, wire.rel_posix(place.index, place.repo))
    return "written"


# ---------- check ------------------------------------------------------------------------------

def strip_block(text):
    try:
        span = find_block(text)
    except ValueError:
        return text
    return text if span is None else text[:span[0]] + text[span[1]:]


def pointers(text):
    """Targets the index points at: markdown link targets and backticked paths (no spaces, no holes).
    A ⟨hole⟩ is still unfilled, so nothing inside it is a pointer yet."""
    text = re.sub(r"⟨[^⟩]*⟩", "", text)
    out = [m.group(1) for m in re.finditer(r"\[[^\]]*\]\(([^)\s]+)\)", text)]
    for m in re.finditer(r"`([^`\s]+)`", text):
        t = m.group(1)
        if ("/" in t or POINTER.search(t.split("#")[0])) and not re.search(r"[<>⟨⟩*${}]", t):
            out.append(t)
    keep = [t for t in out if not re.match(r"^(https?:|mailto:|#)", t) and not t.startswith("/regency")]
    return list(dict.fromkeys(keep))


def anchors_of(path, rel=""):
    """Every anchor a markdown file answers to: each section's label (the §name, or the heading text) and key."""
    out = set()
    for nd in idx.parse(rel or path.name, path.read_bytes())[0]:
        if nd["kind"] == "section":
            out.update({nd["label"], nd["key"], nd["key"].lstrip("§")})
    return out


def resolve_pointer(place, target):
    """(ok, why) for one pointer: the file exists under the index folder, the guidelines root or the repository;
    an anchor must name a section of that file."""
    file_part, _, anchor = target.partition("#")
    file_part = file_part[2:] if file_part.startswith("./") else file_part
    bases = [place.index.parent, place.g, place.repo]
    hit = next((b / file_part for b in bases if (b / file_part).exists()), None)
    if hit is None:
        return False, "dead pointer"
    if anchor and hit.is_file() and hit.suffix.lower() == ".md" and anchor not in anchors_of(hit):
        return False, "dead anchor"
    return True, ""


def map_lines(text):
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"^#{1,6}\s+.*(?i:\bmapa?\b)", line):
            n = 0
            for l in lines[i + 1:]:
                if re.match(r"^#{1,6}\s", l):
                    break
                if l.strip() and not l.lstrip().startswith(">"):  # a blockquote is guidance, not the map
                    n += 1
            return n
    return None


def norm(line):
    return re.sub(r"\s+", " ", line.strip().strip("|").strip())


def check(place):
    """[(kind, detail)] for the entry index. Empty list = clean."""
    if not place.g:
        return [("index", "no guidelines root (library/layouts.md §1)")]
    if not place.index or not place.index.is_file():
        return [("index", ".shortcuts/README.md is missing")]
    raw = place.index.read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n")
    body = strip_block(raw)
    out = []
    for t in pointers(body):
        ok, why = resolve_pointer(place, t)
        if not ok:
            out.append(({"dead pointer": "dead", "dead anchor": "anchor"}[why], f"{t}: {why}"))
    n = map_lines(body)
    if n is not None and n > MAP_LIMIT:
        out.append(("map", f"the map has {n} lines; the limit is {MAP_LIMIT} (what does not fit is a document)"))
    own = {}
    for p in guideline_docs(place):
        if p.resolve() == place.index.resolve():
            continue
        for l in p.read_text(encoding="utf-8-sig", errors="replace").split("\n"):
            k = norm(l)
            if len(k) >= COPY_MIN and not k.startswith("#"):
                own.setdefault(k, g_rel(place, p))
    for l in body.split("\n"):
        k = norm(l)
        if len(k) >= COPY_MIN and k in own:
            out.append(("copy", f"{own[k]}: the index copies a line of it; point to it instead: {k}"))
    keys = [nd["key"] for nd in idx.parse("README.md", raw.encode("utf-8"))[0] if nd["kind"] == "section"]
    for k in sorted({k for k in keys if keys.count(k) > 1}):
        out.append(("anchor", f"README.md#{k}: repeated heading; a citation resolves to the first only"))
    try:
        span = find_block(raw)
    except ValueError as e:
        out.append(("state", str(e)))
        span = False
    if span is None:
        out.append(("state", "no generated state block: shortcuts.py refresh --init"))
    elif span and raw[span[0]:span[1]] != render_state(place):
        out.append(("state", "state block out of date: shortcuts.py refresh"))
    return out


# ---------- guard (hook-acts-guard calls this) -------------------------------------------------

def guard_generated(event, place=None):
    """A reason to deny when a write would hand-edit the generated block of the entry index; else None."""
    path = wire.target_path(event)
    if not path or event.get("tool_name") not in ("Edit", "MultiEdit", "Write"):
        return None
    place = place or locate(path.parent)
    if not place.index or not place.index.is_file() or path.resolve() != place.index.resolve():
        return None
    text = place.index.read_text(encoding="utf-8-sig", errors="replace")
    try:
        span = find_block(text)
    except ValueError:
        return None
    ti = wire.tool_input(event)
    reason = (".shortcuts/README.md: the shortcuts:state block is generated; never edit it by hand (F4): "
              "run shortcuts.py refresh")
    if event.get("tool_name") == "Write":
        new = ti.get("content") or ""
        try:
            new_span = find_block(new)
        except ValueError:
            return reason
        old_block = text[span[0]:span[1]] if span else None
        new_block = new[new_span[0]:new_span[1]] if new_span else None
        return reason if old_block != new_block and span is not None else None
    edits = ti.get("edits") if event.get("tool_name") == "MultiEdit" else [ti]
    for ed in edits or []:
        old, new = (ed or {}).get("old_string") or "", (ed or {}).get("new_string") or ""
        if BEGIN_TAG in old or END in old or BEGIN_TAG in new or END in new:
            return reason
        if span and old:
            at = text.find(old)
            if at >= 0 and at < span[1] and at + len(old) > span[0]:
                return reason
    return None


# ---------- summaries --------------------------------------------------------------------------

def summary_part(place):
    """One fragment for the SessionStart resume line (hook-resume), or None outside adopted projects."""
    if not place.vdir:
        return None
    c, d = check(place), drift(place)
    if any(k == "store" for k, _, _ in d):
        return f"shortcuts check {len(c)} · no store yet (shortcuts.py index)"
    d = [x for x in d if x[0] in ("drift", "gone")]
    return f"shortcuts check {len(c)} · drift {len(d)}" + (" (shortcuts.py peek)" if c or d else "")


def peek(place):
    lines = []
    if place.index and place.index.is_file():
        raw = place.index.read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n")
        lines.append(raw.rstrip("\n"))
        try:
            span = find_block(raw)
        except ValueError:
            span = None
        if not span or raw[span[0]:span[1]] != render_state(place):
            lines += ["", "--- state (live; the block above is absent or out of date) ---", render_state(place)]
    else:
        lines.append("no entry index (.shortcuts/README.md)")
        if place.vdir:
            lines += ["", render_state(place)]
    c = check(place)
    d = drift(place) if place.vdir else []
    lines += ["", f"check: {len(c)} problem(s)"] + [f"  {k:8} {v}" for k, v in c[:10]]
    lines += [f"drift: {len(d)}"] + [f"  {k:9} {r}  {x}".rstrip() for k, r, x in d[:10]]
    lines.append("ledger detail: vp.py ongoing · traces: vp.py trace · exact nodes: idx.py node <path>")
    return "\n".join(lines)


def export(place):
    con = open_db(place, create=False)
    if con is None:
        return {"store": None, "meta": {}, "prints": {}, "nodes": 0}
    try:
        prints = {r[0]: dict(zip(("sha256", "bytes", "mtime_ns", "prev_sha256", "at", "session", "source"), tuple(r)[1:]))
                  for r in con.execute("SELECT * FROM prints ORDER BY path")}
        return {"store": idx.DB, "meta": {r[0]: r[1] for r in con.execute("SELECT k, v FROM meta")},
                "prints": prints, "nodes": con.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]}
    finally:
        con.close()



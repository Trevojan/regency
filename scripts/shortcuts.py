# ---------- command line -----------------------------------------------------------------------

def hook_refresh():
    """SessionEnd entry: silent, never fails, adoption-gated."""
    try:
        event = wire.read_event()
        refresh(locate(event.get("cwd") or os.getcwd()))
    except Exception as e:  # noqa: BLE001 - a recorder never disturbs the session
        sys.stderr.write(f"regency shortcuts refresh error: {type(e).__name__}: {e}\n")
    return 0


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0 if argv else 2
    if "--selftest" in argv:
        return selftest()
    cmd, rest = argv[0], argv[1:]
    if cmd == "refresh" and "--hook" in rest:
        return hook_refresh()
    repo = rest[rest.index("--repo") + 1] if "--repo" in rest and rest.index("--repo") + 1 < len(rest) else None
    place = locate(repo)
    count = "--count" in rest
    if cmd not in ("check", "peek") and not place.vdir:
        print("no .shortcuts/.virtual here: the project has not adopted shortcuts (nothing written)")
        return 0
    if cmd == "index":
        doc = rest[rest.index("--doc") + 1] if "--doc" in rest and rest.index("--doc") + 1 < len(rest) else None
        seen, done = index_all(place, doc)
        print(f"index: {seen} file(s) seen, {done} recorded · store {place.db.relative_to(place.repo).as_posix()}")
        return 0
    if cmd == "record" and rest and not rest[0].startswith("--"):
        print(record(place, Path(rest[0]).resolve(), source="manual") or "ignored (outside the project or in .virtual)")
        return 0
    if cmd == "drift":
        d = drift(place)
        if count:
            print(len(d))
        else:
            for k, r, x in d:
                print(f"{k:9} {r}  {x}".rstrip())
            print(f"{len(d)} drift line(s)")
        return 1 if d else 0
    if cmd == "check":
        c = check(place)
        if count:
            print(len(c))
        else:
            for k, v in c:
                print(f"{k:8} {v}")
            print(f"{len(c)} problem(s)")
        return 1 if c else 0
    if cmd == "refresh":
        r = refresh(place, init="--init" in rest)
        print({"written": "refresh: state block written", "same": "refresh: state block already current",
               "no-block": "refresh: no shortcuts:state block (refresh --init appends one)",
               "no-index": "refresh: .shortcuts/README.md is missing", "broken": "refresh: markers broken, nothing written",
               "no-virtual": "refresh: not adopted"}[r])
        return 0 if r in ("written", "same") else 1
    if cmd == "peek":
        print(peek(place))
        return 0
    if cmd == "migrate":
        con = open_db(place)
        print(meta(con, "migrated_from") or meta(con, "migrate_error") or f"no {LEGACY} to import")
        con.close()
        return 0
    if cmd == "export":
        print(json.dumps(export(place), indent=1, ensure_ascii=False))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

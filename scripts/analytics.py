#!/usr/bin/env python3
"""analytics.py - the analytics lane: analysis passes on an orphan branch, read against two pinned commits.

library/analytics.md. A pass compares the spec (the guidelines root at a commit of main) with the code (a commit
of testing or plumbing). The analyst - suba-recon in direct mode - reads both through `git show <sha>:<path>` and
returns one envelope; this script records it on the orphan `analytics` branch with git's plumbing commands on a
temporary index, so the working tree, the current branch and every uncommitted file stay untouched.

  plan     the packet for one pass, deterministic from git: the two SHAs, the spec documents, the code in the
           scope (baseline) or what changed since the previous pass (delta), the live findings to re-check;
           a delta with nothing changed says so and no pass is needed
  record   check the analyst's envelope (returns.py, suba-recon returns_direct), number the pass AN-## and its
           findings AN-##-##, write manifest.json, findings.json, the four views (gaps, diagnostic, findings,
           suggestions), INDEX.json and the branch README in one commit on `analytics`
  status   passes and live counts                 brief PATH ...   live findings touching those paths
  show ID  one finding whole, with its state      triage ID=STATE[:ARG] ...   the Regent's dispositions
  triage-schema   the elicitation schema for the live findings (scripts/elicit.py): disposition, then the axis
           of a promotion or the reason of a trash; `triage --from-elicit EL-####` records only the answers the
           Regent confirmed in the pop-up

The lane is created only with --create-branch, after the Regent's yes (conventions §5). Nothing here pushes.

Modes:  plan --mode baseline|delta [--spec REF] [--target REF] [--scope PATH ...] · record FILE|- [--create-branch]
        [--trailer LINE ...] · status · brief PATH ... · show ID · triage-schema [ID ...] [--pass AN-##]
        · triage ASSIGNMENT ... | --from-elicit EL-#### [--trailer LINE ...] · --selftest   (each takes --repo DIR)
Pure standard library, Python 3.8+.
"""
import argparse
import collections
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hook_wire as wire  # noqa: E402
import elicit  # noqa: E402  (the triage questions: asked through the engine, answered only by the Regent)
import returns  # noqa: E402  (check_message, extract: the analyst's envelope against its contract)

BRANCH = "analytics"
REMOTE = "origin"
FOLDER = ".analytics"
SUBA = "suba-recon"
KINDS = collections.OrderedDict([("gap", "gaps"), ("diagnostic", "diagnostic"), ("finding", "findings"),
                                 ("suggestion", "suggestions")])
LIVE = ("open", "recycled")
TRIAGE = {"promoted": "to", "recycled": None, "trashed": "why"}
PASS_ID = re.compile(r"^AN-(\d{2,})$")
FINDING_ID = re.compile(r"^AN-\d{2,}-\d{2,}$")
ASSIGN = re.compile(r"^(AN-\d{2,}-\d{2,})=(promoted|recycled|trashed)(?::(.+))?$")
SPEC_SKIP = (FOLDER + "/", ".shortcuts/.virtual/")
MAX_LIST = 400   # paths listed in a packet; past it, counts per folder, and the scope should narrow
GENERATED = "<!-- generated by scripts/analytics.py from findings.json; never edit by hand -->"


class LaneError(RuntimeError):
    """A refusal with its reason: printed on one line, exit 2."""


# ---------- git --------------------------------------------------------------------------------

def git(repo, *args, data=None, env=None):
    r = subprocess.run(["git", "-C", str(repo), *args], input=data, capture_output=True, env=env, timeout=120)
    if r.returncode != 0:
        msg = r.stderr.decode("utf-8", "replace").strip() or f"exit {r.returncode}"
        raise LaneError(f"git {args[0]}: {msg[:300]}")
    return r.stdout.decode("utf-8", "replace")


def try_git(repo, *args):
    try:
        return git(repo, *args)
    except (LaneError, OSError, subprocess.SubprocessError):
        return None


def rev(repo, ref):
    """The full SHA of a commit, or None."""
    out = try_git(repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}") if ref else None
    return out.strip() or None if out else None


def lane_tip(repo):
    """(sha, 'local' | 'origin') of the lane, or (None, None)."""
    for ref, where in ((f"refs/heads/{BRANCH}", "local"), (f"refs/remotes/{REMOTE}/{BRANCH}", REMOTE)):
        sha = rev(repo, ref)
        if sha:
            return sha, where
    return None, None


def show(repo, sha, path):
    return try_git(repo, "show", f"{sha}:{path}") if sha else None


def ls_tree(repo, sha, under=""):
    out = try_git(repo, "ls-tree", "-r", "--name-only", "-z", sha, *([under] if under else [])) or ""
    return [p for p in out.split("\0") if p]


def write_lane(repo, files, message, create=False):
    """One commit on the lane holding `files` ({path: text}) over its current tree. Returns the commit."""
    tip, _ = lane_tip(repo)
    if tip is None and not create:
        raise LaneError(f"no `{BRANCH}` branch here: ask the Regent, then run again with --create-branch")
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, GIT_INDEX_FILE=str(Path(tmp) / "index"))
        git(repo, "read-tree", *([tip] if tip else ["--empty"]), env=env)
        for path, text in sorted(files.items()):
            blob = git(repo, "hash-object", "-w", "--stdin", data=text.encode("utf-8")).strip()
            git(repo, "update-index", "--add", "--cacheinfo", f"100644,{blob},{path}", env=env)
        tree = git(repo, "write-tree", env=env).strip()
    commit = git(repo, "commit-tree", tree, *(["-p", tip] if tip else []), data=message.encode("utf-8")).strip()
    old = rev(repo, f"refs/heads/{BRANCH}") or "0" * len(commit)
    git(repo, "update-ref", "-m", "analytics.py", f"refs/heads/{BRANCH}", commit, old)
    return commit


# ---------- the lane's state -------------------------------------------------------------------

def guidelines_rel(repo, sha=None):
    g = wire.guidelines_root(repo)
    if g is not None:
        return wire.rel_posix(g, repo)
    for rel in wire.GUIDELINE_ROOTS:
        if sha and try_git(repo, "cat-file", "-e", f"{sha}:{rel}") is not None:
            return rel
    return wire.GUIDELINE_ROOTS[0]


def load(repo):
    """(index, guidelines rel, tip). An empty index when the lane does not exist."""
    tip, _ = lane_tip(repo)
    for rel in wire.GUIDELINE_ROOTS:
        text = show(repo, tip, f"{rel}/{FOLDER}/INDEX.json")
        if text:
            idx = json.loads(text)
            return idx, idx.get("guidelines") or rel, tip
    g = guidelines_rel(repo)
    return {"schema": 1, "guidelines": g, "passes": [], "findings": {}}, g, tip


def live(idx):
    return {k: f for k, f in idx["findings"].items() if f.get("state") in LIVE}


def next_pass(idx):
    nums = [int(PASS_ID.match(p["id"]).group(1)) for p in idx["passes"] if PASS_ID.match(p.get("id", ""))]
    return f"AN-{(max(nums) + 1 if nums else 1):02d}"


def bare(ref):
    """`src/a.py:42` or `X.md#anchor` -> the path alone."""
    return re.sub(r"(:\d+(-\d+)?|#.*)$", "", (ref or "").strip()).strip("/")


def touches(a, b):
    a, b = bare(a), bare(b)
    return bool(a and b) and (a == b or a.startswith(b + "/") or b.startswith(a + "/"))


def finding_paths(f, g):
    out = [bare(w) for w in f.get("where") or []]
    if f.get("against"):
        a = bare(f["against"])
        out.append(a if a.startswith(g + "/") else f"{g}/{a}")
    return [p for p in out if p]


def in_scope(path, scope):
    return not scope or any(touches(path, s) for s in scope)


def spec_doc(path, g):
    inner = path[len(g) + 1:] if path.startswith(g + "/") else None
    return inner is not None and not inner.startswith(SPEC_SKIP)


# ---------- plan -------------------------------------------------------------------------------

def default_target(repo):
    for ref in ("testing", "plumbing"):
        if rev(repo, ref):
            return ref
    return "HEAD"


def changed(repo, a, b, under=""):
    out = git(repo, "diff", "--name-only", "-z", "-M", a, b, *(["--", under] if under else []))
    return sorted(p for p in out.split("\0") if p)


def recheck(idx, g, code_changed, spec_changed):
    touched = list(code_changed) + list(spec_changed)
    return [k for k, f in sorted(live(idx).items()) if any(touches(p, t) for p in finding_paths(f, g) for t in touched)]


def listing(paths):
    if len(paths) <= MAX_LIST:
        return {"count": len(paths), "list": paths}
    folders = collections.Counter(p.split("/", 1)[0] if "/" in p else "." for p in paths)
    return {"count": len(paths), "list": None, "by_folder": dict(folders.most_common()),
            "narrow": "past the listing limit: pass --scope to the folders the pass needs"}


def plan(repo, mode, spec_ref="main", target_ref=None, scope=()):
    spec_sha = rev(repo, spec_ref)
    if not spec_sha:
        raise LaneError(f"spec ref `{spec_ref}` is not a commit here")
    target_ref = target_ref or default_target(repo)
    target_sha = rev(repo, target_ref)
    if not target_sha:
        raise LaneError(f"code ref `{target_ref}` is not a commit here")
    idx, g, _ = load(repo)
    g = idx.get("guidelines") or guidelines_rel(repo, spec_sha)
    scope = sorted({bare(s) for s in scope if bare(s)})
    prev = idx["passes"][-1] if idx["passes"] else None
    packet = {"mode": mode, "pass": next_pass(idx), "previous": prev["id"] if prev else None,
              "spec": {"ref": spec_ref, "sha": spec_sha}, "target": {"ref": target_ref, "sha": target_sha},
              "guidelines": g, "scope": scope,
              "read": {"spec": f"git show {spec_sha[:12]}:<path>", "code": f"git show {target_sha[:12]}:<path>",
                       "search": f"git grep -n <pattern> {target_sha[:12]} -- <paths>",
                       "lineage": "python scripts/vp.py code <path>"},
              "return": f"python scripts/returns.py template {SUBA} --direct"}
    if mode == "baseline":
        spec = [p for p in ls_tree(repo, spec_sha, g) if spec_doc(p, g)]
        code = [p for p in ls_tree(repo, target_sha) if in_scope(p, scope) and not touches(p, g)]
        packet.update(spec_docs=listing(spec), code_files=listing(code),
                      recheck=sorted(live(idx)), still_valid=0)
        return packet
    if prev is None:
        raise LaneError("no previous pass: run /regency:repository-analytics-baseline first")
    try:
        code_changed = [p for p in changed(repo, prev["target"]["sha"], target_sha)
                        if in_scope(p, scope) and not touches(p, g)]
        spec_changed = [p for p in changed(repo, prev["spec"]["sha"], spec_sha, g) if spec_doc(p, g)]
    except LaneError as e:
        raise LaneError(f"the previous pass's commits are not reachable ({e}); run a baseline")
    again = recheck(idx, g, code_changed, spec_changed)
    packet.update(code_changed=listing(code_changed), spec_changed=listing(spec_changed), recheck=again,
                  still_valid=len(live(idx)) - len(again),
                  nothing_changed=not code_changed and not spec_changed)
    return packet


# ---------- record -----------------------------------------------------------------------------

def envelope_of(text):
    """The analyst's envelope, or LaneError with the gate's misses."""
    checked = returns.check_message(text, SUBA, direct=True)
    if not checked:
        raise LaneError(f"no {SUBA} envelope in the return (returns.py template {SUBA} --direct)")
    _, misses, _ = checked[0]
    if misses:
        raise LaneError("the return misses its contract: " + " · ".join(f"{p}: {m}" for p, m in misses[:6]))
    found, _ = returns.extract(text)
    return next(env for env, _ in found if env and env.get("suba") == SUBA)


def view(pid, kind, rows, manifest):
    out = [f"# {pid} · {KINDS[kind]}", "", GENERATED, "",
           f"{manifest['mode']} · spec `{manifest['spec']['sha'][:12]}` · code `{manifest['target']['sha'][:12]}`"
           f" · {manifest['at']}", ""]
    if not rows:
        out.append("None in this pass.")
    for f in rows:
        out += [f"## {f['id']} · {f['title']}", "", f"- observed: {f['observed']}"]
        if f.get("inferred"):
            out.append(f"- inferred: {f['inferred']}")
        if f.get("against"):
            out.append(f"- against: `{f['against']}`")
        out.append("- where: " + ", ".join(f"`{w}`" for w in f["where"]))
        out.append("- evidence:")
        out += [f"  - {e}" for e in f["evidence"]]
        out += [f"- destination: `{f['destination']}` · key: `{f['key']}`", ""]
    return "\n".join(out).rstrip() + "\n"


def readme(idx):
    g = idx["guidelines"]
    lines = [f"# {BRANCH}", "", GENERATED.replace(" from findings.json", ""), "",
             "The report-only lane of regency (`library/analytics.md`): one folder per analysis pass under "
             f"`{g}/{FOLDER}/`, each read against two pinned commits. Residue until the Regent triages it: never "
             "merged, never a norm.", "",
             "| pass | mode | at | spec | code | findings | live |", "|---|---|---|---|---|---|---|"]
    lv = live(idx)
    for p in reversed(idx["passes"]):
        n_live = sum(1 for f in lv.values() if f["pass"] == p["id"])
        lines.append(f"| `{p['id']}` | {p['mode']} | {p['at'][:10]} | `{p['spec']['sha'][:7]}` | "
                     f"`{p['target']['sha'][:7]}` | {p['findings']} | {n_live} |")
    lines += ["", "## Live findings", ""]
    if not lv:
        lines.append("None.")
    else:
        lines += ["| id | kind | state | title | where |", "|---|---|---|---|---|"]
        for k, f in sorted(lv.items()):
            title = f["title"].replace("|", "/")
            lines.append(f"| `{k}` | {f['kind']} | {f['state']} | {title} | `{bare((f.get('where') or [''])[0])}` |")
    return "\n".join(lines) + "\n"


def note(f, state, **extra):
    f["state"] = state
    f.setdefault("history", []).append(dict({"at": wire.now(), "state": state}, **extra))


def message(subject, trailers):
    return subject + ("\n\n" + "\n".join(trailers) if trailers else "") + "\n"


def record(repo, text, create=False, trailers=()):
    env = envelope_of(text)
    body = env["body"]
    pk = body["packet"]
    spec_sha, target_sha = rev(repo, pk["spec_sha"]), rev(repo, pk["target_sha"])
    if not spec_sha or not target_sha:
        raise LaneError("the packet's spec_sha or target_sha is not a commit here")
    idx, g, _ = load(repo)
    idx["guidelines"] = g
    prev = idx["passes"][-1] if idx["passes"] else None
    if pk["mode"] == "delta" and prev is None:
        raise LaneError("a delta needs a previous pass: run the baseline first")
    pid, at = next_pass(idx), wire.now()
    findings = [dict({"id": f"{pid}-{i:02d}"}, **f) for i, f in enumerate(body["findings"], 1)]
    lv = live(idx)
    still, cleared = [], []
    for c in body["carried"]:
        f = lv.get(c["id"])
        if f is None:
            raise LaneError(f"{c['id']} is not a live finding of this lane")
        if c["status"] == "cleared":
            note(f, "cleared", by=SUBA, **{"pass": pid})
            cleared.append(c["id"])
        else:
            f.setdefault("history", []).append({"at": at, "state": f["state"], "seen": pid})
            still.append(c["id"])
    if prev is None:
        expected = sorted(lv)
    elif pk["mode"] == "baseline":
        expected = sorted(lv)
    else:
        expected = recheck(idx, g, [p for p in changed(repo, prev["target"]["sha"], target_sha) if not touches(p, g)],
                           [p for p in changed(repo, prev["spec"]["sha"], spec_sha, g) if spec_doc(p, g)])
    answered = set(still) | set(cleared)
    unanswered = [k for k in expected if k not in answered]
    manifest = {"id": pid, "mode": pk["mode"], "at": at, "previous": prev["id"] if prev else None,
                "spec": {"sha": spec_sha}, "target": {"sha": target_sha}, "guidelines": g,
                "scope": pk.get("scope") or [],
                "findings": dict(collections.Counter(f["kind"] for f in findings)),
                "carried": {"still": still, "cleared": cleared, "unanswered": unanswered},
                "not_inspected": body["not_inspected"], "doubts": env.get("doubts") or [],
                "terminal": env.get("terminal")}
    for f in findings:
        idx["findings"][f["id"]] = {"pass": pid, "kind": f["kind"], "title": f["title"], "where": f["where"],
                                    "against": f.get("against"), "destination": f["destination"], "key": f["key"],
                                    "state": "open", "history": [{"at": at, "state": "open", "pass": pid}]}
    idx["passes"].append({"id": pid, "mode": pk["mode"], "at": at, "spec": {"sha": spec_sha},
                          "target": {"sha": target_sha}, "findings": len(findings)})
    base = f"{g}/{FOLDER}"
    files = {f"{base}/{pid}/manifest.json": json.dumps(manifest, ensure_ascii=False, indent=1) + "\n",
             f"{base}/{pid}/findings.json": json.dumps({"findings": findings, "carried": body["carried"],
                                                        "not_inspected": body["not_inspected"]},
                                                       ensure_ascii=False, indent=1) + "\n",
             f"{base}/INDEX.json": json.dumps(idx, ensure_ascii=False, indent=1) + "\n",
             "README.md": readme(idx)}
    for kind, name in KINDS.items():
        files[f"{base}/{pid}/{name}.md"] = view(pid, kind, [f for f in findings if f["kind"] == kind], manifest)
    subject = (f"analytics: {pid} {pk['mode']} - {len(findings)} finding(s), spec {spec_sha[:7]}, "
               f"code {target_sha[:7]}")
    commit = write_lane(repo, files, message(subject, trailers), create)
    return {"pass": pid, "commit": commit, "branch": BRANCH, "findings": manifest["findings"],
            "carried": manifest["carried"], "live": len(live(idx)),
            "push": f"git push -u {REMOTE} {BRANCH}"}


# ---------- read and triage --------------------------------------------------------------------

def status(repo):
    idx, g, tip = load(repo)
    _, where = lane_tip(repo)
    counts = collections.Counter(f.get("state") for f in idx["findings"].values())
    lines = [f"analytics: branch {where or 'absent'} · passes {len(idx['passes'])} · live "
             f"{counts['open'] + counts['recycled']} (open {counts['open']}, recycled {counts['recycled']}) · "
             f"promoted {counts['promoted']} · trashed {counts['trashed']} · cleared {counts['cleared']}"]
    lv = live(idx)
    for p in idx["passes"]:
        n_live = sum(1 for f in lv.values() if f["pass"] == p["id"])
        lines.append(f"{p['id']} {p['mode']} {p['at'][:10]} spec {p['spec']['sha'][:7]} code "
                     f"{p['target']['sha'][:7]} · {p['findings']} finding(s), {n_live} live")
    lines += [f"live {k} {f['kind']} {f['state']} -> {f.get('destination')} · {bare((f.get('where') or [''])[0])}"
              f" - {f['title']}" for k, f in sorted(lv.items())]
    return lines


def brief(repo, paths):
    idx, g, tip = load(repo)
    if tip is None:
        return ["analytics: no lane here"]
    want = []
    for p in paths:
        q = Path(p)
        want.append(wire.rel_posix(q if q.is_absolute() else Path.cwd() / q, repo) or bare(p))
    rows = [f"{k} {f['kind']} {bare((f.get('where') or [''])[0])} - {f['title']} (analytics.py show {k})"
            for k, f in sorted(live(idx).items())
            if any(touches(fp, w) for fp in finding_paths(f, g) for w in want)]
    return rows or ["analytics: no live finding touches these paths"]


def finding(repo, fid):
    if not FINDING_ID.match(fid or ""):
        raise LaneError(f"`{fid}` is not a finding id (AN-##-##)")
    idx, g, tip = load(repo)
    f = idx["findings"].get(fid)
    if f is None:
        raise LaneError(f"{fid} is not in this lane")
    text = show(repo, tip, f"{g}/{FOLDER}/{f['pass']}/findings.json")
    whole = next((x for x in json.loads(text)["findings"] if x["id"] == fid), {}) if text else {}
    return dict(whole, state=f["state"], history=f.get("history", []))


def triage(repo, assignments, trailers=()):
    idx, g, tip = load(repo)
    if tip is None:
        raise LaneError("no analytics lane here")
    done = []
    for a in assignments:
        m = ASSIGN.match(a.strip())
        if not m:
            raise LaneError(f"`{a}`: write ID=promoted:<path#anchor>, ID=recycled or ID=trashed:<reason>")
        fid, state, arg = m.group(1), m.group(2), (m.group(3) or "").strip()
        f = idx["findings"].get(fid)
        if f is None or f.get("state") not in LIVE:
            raise LaneError(f"{fid} is not a live finding (state {f.get('state') if f else 'absent'})")
        need = TRIAGE[state]
        if need and not arg:
            raise LaneError(f"{fid}={state} needs {':' + need} (promoted:<path#anchor>, trashed:<reason>)")
        note(f, state, by="regent", **({need: arg} if need else {}))
        done.append(f"{fid}={state}")
    if not done:
        raise LaneError("nothing to triage")
    files = {f"{g}/{FOLDER}/INDEX.json": json.dumps(idx, ensure_ascii=False, indent=1) + "\n", "README.md": readme(idx)}
    commit = write_lane(repo, files, message(f"analytics: triage - {', '.join(done)}", trailers))
    return {"commit": commit, "triaged": done, "live": len(live(idx)), "push": f"git push -u {REMOTE} {BRANCH}"}


# ---------- triage through the elicitation engine --------------------------------------------

TRIAGE_SCHEMA = "analytics-triage"
AXES = (".plan", "ledger", ".decisions", ".sources", ".constraints")
AXIS_NOTE = {".plan": "authorised by the Regent, not yet built", "ledger": "a backlog item in the work ledger",
             ".decisions": "a dated decision, in the Regent's words", ".sources": "a source that decided something",
             ".constraints": "a rule of the artefact, in the Regent's words"}


def slot_of(prefix, fid):
    return f"{prefix}_{fid.lower().replace('-', '_')}"


def header_of(fid, suffix=""):
    text = f"{fid} {suffix}".strip()
    return text if len(text) <= elicit.HEADER_MAX else f"{fid[-(elicit.HEADER_MAX - len(suffix) - 1):]} {suffix}"


def triage_schema(repo, ids=(), pass_id=None):
    """The elicitation schema for the live findings: generated from INDEX.json by this script, never by an agent."""
    idx, _, tip = load(repo)
    lv = live(idx)
    unknown = [i for i in ids if i not in lv]
    if unknown:
        raise LaneError("not live in this lane: " + ", ".join(unknown))
    pick = [k for k in sorted(lv) if (not ids or k in ids) and (not pass_id or lv[k]["pass"] == pass_id)]
    if not pick:
        raise LaneError("no live finding to triage")
    qs = []
    for n, k in enumerate(pick):
        f, d = lv[k], slot_of("d", k)
        dest = f.get("destination") if f.get("destination") in AXES else ".plan"
        axes = [dest] + [a for a in AXES if a != dest][:3]
        title = f"{k} ({f['kind']}, {bare((f.get('where') or [''])[0])}): {f['title']} - promote, recycle or trash?"
        qs += [{"id": f"D_{k}", "slot": d, "header": header_of(k), "order": n * 10,
                "prompt": title.replace("{", "(").replace("}", ")"),
                "options": [{"value": "promoted", "label": "Promote", "description": f"written into {dest} on the working branch"},
                            {"value": "recycled", "label": "Recycle", "description": "kept live: the next delta re-checks it"},
                            {"value": "trashed", "label": "Trash", "description": "discarded, with its reason"}]},
               {"id": f"P_{k}", "slot": slot_of("p", k), "header": header_of(k, "to"), "order": n * 10 + 1,
                "depends_on": [d], "when": {"param": d, "equals": "promoted"}, "other": True,
                "prompt": f"{k} ({{{d}}}): into which axis does it land?",
                "options": [{"value": a, "label": a, "description": AXIS_NOTE[a]} for a in axes]},
               {"id": f"R_{k}", "slot": slot_of("r", k), "header": header_of(k, "why"), "order": n * 10 + 2,
                "depends_on": [d], "when": {"param": d, "equals": "trashed"}, "other": True,
                "prompt": f"{k} ({{{d}}}): why is it trashed?",
                "options": [{"value": "wrong observation", "label": "Wrong observation",
                             "description": "what was observed does not hold"},
                            {"value": "duplicate", "label": "Duplicate", "description": "another finding says the same"},
                            {"value": "out of scope", "label": "Out of scope", "description": "not this project's concern"}]}]
    schema = {"schema": TRIAGE_SCHEMA, "version": 1,
              "about": "generated by analytics.py triage-schema from the analytics lane's live findings", "questions": qs}
    bad = elicit.problems(schema)
    if bad:
        raise LaneError("the generated triage schema does not hold: " + " · ".join(bad[:4]))
    return schema


def triage_from_elicit(repo, sid, trailers=()):
    """Record the dispositions the Regent confirmed in the pop-up; an agent's proposal records nothing."""
    store = elicit.Store(repo)
    try:
        st = elicit.status(store, sid)
    finally:
        store.close()
    if st["schema"] != TRIAGE_SCHEMA:
        raise LaneError(f"{sid} is not a triage session ({st['schema']})")
    qs, params = st["questions"], st["parameters"]

    def regent(prefix, k):
        q = qs.get(f"{prefix}_{k}")
        p = params.get(q["slot"]) if q else None
        ok = q and q["status"] == "answered" and p and p["status"] == "confirmed" and p["source"] == "regent"
        return p["value"] if ok else None

    assignments, undecided, done = [], [], []
    lv = live(load(repo)[0])
    for qid in qs:
        if not qid.startswith("D_"):
            continue
        k = qid[2:]
        if k not in lv:
            done.append(k)       # triaged already, by an earlier run over this session
            continue
        d = regent("D", k)
        arg = {"promoted": regent("P", k), "trashed": regent("R", k), "recycled": ""}.get(d) if d else None
        if d is None or arg is None:
            undecided.append(k)
            continue
        assignments.append(f"{k}={d}" + (f":{arg}" if arg else ""))
    if not assignments:
        raise LaneError("no finding has the Regent's complete answer yet: " + ", ".join(undecided))
    out = triage(repo, assignments, trailers)
    return dict(out, session=sid, undecided=undecided, already=done)



def envelope(pk, findings, carried=()):
    body = {"packet": {"mode": pk["mode"], "spec_sha": pk["spec"]["sha"][:12], "target_sha": pk["target"]["sha"][:12],
                       "scope": pk["scope"]},
            "findings": findings, "carried": list(carried), "not_inspected": ["tests: none exist yet"]}
    env = {"envelope": 1, "suba": SUBA, "via": "direct", "body": body,
           "terminal": {"state": "SUCCESS", "why": "the scope was read whole"}}
    return "```json\n" + json.dumps(env) + "\n```\n"


